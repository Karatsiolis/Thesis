# ILP / OPTA skeleton
# ============================================================

def build_ilp_problem(system: SystemInputs) -> dict:
    """
    Optimal (OPTA) ILP formulation for the AV / V2I / subtask scenario.
    Connect to CPLEX / Gurobi / PuLP to solve.
    """
    return {
        "objective": "min  sum_{i,s,j} finish_time(i,s,j) * X_isj",
        "decision_variables": [
            "X_isj ∈ {0,1} : subtask s of task i assigned to BS j"
        ],
        "constraints": [
            "C1: sum_j X_isj = 1                  for all (i,s)  [unique assignment]",
            "C2: X_isj = 0  if j ∉ route(i)       for all (i,s,j)[route reachability]",
            "C3: finish(i,s,j) ≤ t_exit(i,j)      for all (i,s,j)[V2I window]",
            "C4: finish(i,s) ≤ deadline(i,s)       for all (i,s)  [subtask deadline]",
            "C5: start(i,s+1) ≥ finish(i,s)        for all (i,s)  [sequential order]",
            "C6: sum_{i,s} X_isj ≤ C_max_j         for all j      [server capacity]",
            "C7: sum_s delay(i,s) ≤ tau_i           for all i      [task deadline]",
        ],
    }


