from __future__ import annotations

from dataclasses import dataclass, field
from math import inf
from typing import Dict, List, Tuple, Literal, Optional


# ============================================================
# Data structures
# ============================================================

@dataclass
class SubTask:
    """
    Atomic unit of computation assigned to exactly one MEC server via V2I.
    Each Task is decomposed into an ordered sequence of SubTasks.
    SubTask s+1 cannot begin until SubTask s has finished (sequential dependency).
    """
    subtask_id: int
    parent_task_id: int
    D_in: float          # input data size (bits)
    D_out: float         # result data size (bits)
    omega: float         # required CPU cycles
    deadline: float      # absolute deadline for this subtask (s from t=0)
    order: int           # execution order within the parent task (0-based)

    earliest_start: float
    # Earliest time the AV can begin uploading this subtask (s from t=0).
    # For order=0 this is typically when the task is generated.
    # For order>0 it acts as a lower bound; the real start is determined
    # dynamically from last_finish of the previous subtask.

    bs_time_windows: Dict[int, Tuple[float, float]] = field(default_factory=dict)
    # bs_time_windows[bs_id] = (t_enter, t_exit)
    # The interval during which the AV is within V2I range of BS bs_id.
    # A BS absent from this dict is NOT reachable by this AV.


@dataclass
class Task:
    """
    A computation task generated by an autonomous vehicle.
    Decomposed into sequentially-ordered SubTasks, each executed on a MEC server.
    """
    task_id: int
    av_id: int             # ID of the AV that generated this task
    subtasks: List[SubTask]
    tau: float             # maximum allowable total end-to-end delay (s)


@dataclass
class MECServer:
    """
    MEC server co-located with a Road-Side Unit / Base Station.
    Resources are evenly divided among C_max simultaneously processed tasks
    (paper assumption).

    Simplification note: C_max is treated as the maximum number of subtasks
    the server accepts across the entire scheduling window, not a strict
    concurrency interval check. This is a conservative approximation.
    """
    bs_id: int
    F_total: float         # total CPU frequency (Hz)
    C_max: int             # max simultaneous tasks

    @property
    def f_alloc(self) -> float:
        if self.C_max <= 0:
            raise ValueError(f"C_max must be > 0 for BS {self.bs_id}")
        return self.F_total / self.C_max


@dataclass
class SystemInputs:
    tasks: List[Task]
    servers: Dict[int, MECServer]

    # R_av_bs[(av_id, bs_id)] = V2I rate between AV i and BS j (bps).
    # An AV can generate multiple tasks. The rate depends on the vehicle, not the task
    R_av_bs: Dict[Tuple[int, int], float]


@dataclass
class AlgorithmOutput:
    """
    Full scheduling result.

    assignments[(task_id, subtask_id)] = bs_id
    D[(task_id, subtask_id)]           = end-to-end delay of that subtask (s)
    start_times[(task_id, subtask_id)] = actual upload start time (s)
    finish_times[(task_id, subtask_id)]= time result is delivered to AV (s)
    task_delays[task_id]               = sum of subtask delays for the task (s)
    total_cost                         = sum of all feasible task delays (s)
    failed_subtasks                    = list of (task_id, subtask_id) with no
                                         feasible server assignment
    """
    assignments: Dict[Tuple[int, int], int]
    D: Dict[Tuple[int, int], float]
    start_times: Dict[Tuple[int, int], float]
    finish_times: Dict[Tuple[int, int], float]
    task_delays: Dict[int, float]
    total_cost: float
    failed_subtasks: List[Tuple[int, int]]


# ============================================================
# Helpers
# ============================================================

def get_task_by_id(tasks: List[Task], task_id: int) -> Task:
    for task in tasks:
        if task.task_id == task_id:
            return task
    raise ValueError(f"Task {task_id} not found")


def get_next_subtask(task: Task, next_order: int) -> Optional[SubTask]:
    """Return the subtask with the given order index, or None if done."""
    for st in task.subtasks:
        if st.order == next_order:
            return st
    return None


# ============================================================
# Delay model  (V2I only, MEC execution, no migration, no caching)
# ============================================================

def upload_delay(subtask: SubTask, R_av_bs: float) -> float:
    """AV → BS upload time. Eq. (7) of the paper."""
    return subtask.D_in / R_av_bs


def mec_compute_delay(subtask: SubTask, server: MECServer) -> float:
    """MEC server execution time. Eq. (9) of the paper."""
    return subtask.omega / server.f_alloc


def return_delay(subtask: SubTask, R_av_bs: float) -> float:
    """BS → AV result download time. Eq. (12) of the paper."""
    return subtask.D_out / R_av_bs


def total_subtask_delay(subtask: SubTask, server: MECServer, R_av_bs: float) -> float:
    """
    Full end-to-end delay for one subtask offloaded to a MEC server:
        delay = upload + compute + download
    Corresponds to Eq. (14) of the paper (the only execution branch in this
    model: no local processing, no caching, no migration).
    """
    return (
        upload_delay(subtask, R_av_bs)
        + mec_compute_delay(subtask, server)
        + return_delay(subtask, R_av_bs)
    )


# ============================================================
# Route-aware feasibility and cost
# ============================================================

def compute_assignment(
    subtask: SubTask,
    server: MECServer,
    bs_id: int,
    R_av_bs: float,
    last_finish: float,
) -> Optional[Tuple[float, float, float]]:
    """
    Evaluate assigning subtask to bs_id given that the previous subtask of
    the same task finished at last_finish.

    Returns (t_start, t_finish, delay) if feasible, else None.

    Feasibility conditions:
    1. BS is on the AV route  (bs_id in subtask.bs_time_windows).
    2. The AV is within V2I range during upload AND result delivery.
    3. The subtask deadline is met.

    t_start accounts for three lower bounds:
    - last_finish      : sequential dependency on the previous subtask
    - subtask.earliest_start : earliest the AV is allowed to start uploading
    - t_enter          : the AV must be in range to begin uploading
    """
    if bs_id not in subtask.bs_time_windows:
        return None

    t_enter, t_exit = subtask.bs_time_windows[bs_id]

    t_start = max(last_finish, subtask.earliest_start, t_enter)

    if t_start > t_exit:
        return None   # AV has already left range before it can start

    delay = total_subtask_delay(subtask, server, R_av_bs)
    t_finish = t_start + delay

    if t_finish > t_exit:
        return None   # result not ready before AV leaves range

    if t_finish > subtask.deadline:
        return None   # individual subtask deadline violated

    return t_start, t_finish, delay


# ============================================================
# RASMHA — Route-Aware Subtask MEC Heuristic Algorithm
# ============================================================

def rasmha(system: SystemInputs) -> AlgorithmOutput:
    """
    Route-Aware Subtask MEC Heuristic Algorithm (RASMHA).

    Adapted from the greedy structure of CMHA (Algorithm 1 of the paper) for
    the autonomous vehicle scenario:
      - V2I communication only (no V2V, no inter-BS migration).
      - MEC-only execution (no local processing fallback).
      - No result caching.
      - Tasks are decomposed into sequentially-ordered SubTasks.
      - Each SubTask is assigned independently to one MEC server.
      - SubTask s+1 of a task cannot start until SubTask s has finished.

    Greedy criterion: at each step, assign the SubTask–BS pair that minimises
    finish_time (= t_start + delay).  Using finish_time rather than delay
    alone captures the route timing of the AV: a faster server that the AV
    reaches later may produce a worse overall finish time.

    The cost candidates are rebuilt dynamically each iteration so that
    sequential finish times are propagated exactly (no static approximation).

    Capacity simplification: C_max is treated as the total number of SubTasks
    a server accepts across the scheduling window (conservative approximation
    of true concurrency; noted as a simplification in the thesis).
    """

    # Current load per BS
    C_N: Dict[int, int] = {bs_id: 0 for bs_id in system.servers}

    # For each task: the order index of the next subtask waiting to be assigned
    next_order: Dict[int, int] = {task.task_id: 0 for task in system.tasks}

    # Finish time of the last assigned subtask per task (= earliest start of next)
    last_finish: Dict[int, float] = {task.task_id: 0.0 for task in system.tasks}

    # Output containers
    assignments: Dict[Tuple[int, int], int] = {}
    D: Dict[Tuple[int, int], float] = {}
    start_times: Dict[Tuple[int, int], float] = {}
    finish_times: Dict[Tuple[int, int], float] = {}
    failed_subtasks: List[Tuple[int, int]] = []

    # Tasks that still have subtasks left to schedule
    active_tasks = {task.task_id for task in system.tasks}

    # --------------------------------------------------------
    # Greedy loop — one subtask assigned per iteration
    # --------------------------------------------------------
    while active_tasks:
        best_cost = inf          # best finish_time seen this iteration
        best = None              # (task_id, subtask_id, bs_id)
        best_vals = None         # (t_start, t_finish, delay)

        # Build candidates dynamically: only the *next* subtask of each task
        for task_id in active_tasks:
            task = get_task_by_id(system.tasks, task_id)
            subtask = get_next_subtask(task, next_order[task_id])
            if subtask is None:
                continue

            for bs_id, server in system.servers.items():
                R = system.R_av_bs.get((task.av_id, bs_id))
                if R is None or R <= 0:
                    continue
                if C_N[bs_id] >= server.C_max:
                    continue  # server full, skip immediately

                result = compute_assignment(
                    subtask, server, bs_id, R, last_finish[task_id]
                )
                if result is None:
                    continue

                t_start, t_finish, delay = result

                # Criterion: minimise finish_time
                if t_finish < best_cost:
                    best_cost = t_finish
                    best = (task_id, subtask.subtask_id, bs_id)
                    best_vals = (t_start, t_finish, delay)

        if best is None:
            # No feasible assignment exists for any remaining next-subtask.
            # Mark all pending subtasks of all active tasks as failed.
            for task_id in active_tasks:
                task = get_task_by_id(system.tasks, task_id)
                for st in sorted(task.subtasks, key=lambda s: s.order):
                    if st.order >= next_order[task_id]:
                        failed_subtasks.append((task_id, st.subtask_id))
            break

        task_id, subtask_id, bs_id = best
        t_start, t_finish, delay = best_vals

        # Commit the assignment
        C_N[bs_id] += 1
        assignments[(task_id, subtask_id)] = bs_id
        D[(task_id, subtask_id)] = delay
        start_times[(task_id, subtask_id)] = t_start
        finish_times[(task_id, subtask_id)] = t_finish
        last_finish[task_id] = t_finish
        next_order[task_id] += 1

        # Check whether this task has more subtasks to schedule
        task = get_task_by_id(system.tasks, task_id)
        if get_next_subtask(task, next_order[task_id]) is None:
            active_tasks.discard(task_id)

    # --------------------------------------------------------
    # Aggregate per-task delays and total cost
    # --------------------------------------------------------
    task_delays: Dict[int, float] = {}
    for task in system.tasks:
        subtask_delays = [
            D.get((task.task_id, st.subtask_id), inf)
            for st in task.subtasks
        ]
        task_delays[task.task_id] = sum(subtask_delays)

    # Total cost counts only fully feasible tasks; failed ones are reported
    # separately so the metric is not silently underestimated.
    feasible_task_delays = [
        d for task_id, d in task_delays.items()
        if not any(tid == task_id for tid, _ in failed_subtasks)
    ]
    total_cost = sum(feasible_task_delays)

    return AlgorithmOutput(
        assignments=assignments,
        D=D,
        start_times=start_times,
        finish_times=finish_times,
        task_delays=task_delays,
        total_cost=total_cost,
        failed_subtasks=failed_subtasks,
    )


