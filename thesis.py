# ============================================================
# Algorithm 2 main
# ============================================================

def mobility_aware_task_offloading_main(
    tasks: List[Task],
    servers: Dict[int, MECServer],
    R_av_bs: Dict[Tuple[int, int], float],
    method: Literal["RASMHA", "OPTA"] = "RASMHA",
    av_history_data=None,
    current_av_locations=None,
) -> AlgorithmOutput:
    """
    Algorithm 2 — AV / V2I task offloading main loop:
      1. Trajectory prediction
      2. Information gathering  →  SystemInputs
      3. Solve via RASMHA or OPTA
      4. Execute decisions
      5. Transmit results to AV
    """
    prediction_model = build_trajectory_prediction_model(av_history_data)

    system = information_gathering(
        current_av_locations=current_av_locations,
        prediction_model=prediction_model,
        tasks=tasks,
        servers=servers,
        R_av_bs=R_av_bs,
    )

    if method.upper() == "OPTA":
        ilp_problem = build_ilp_problem(system)
        solve_with_opta(ilp_problem)   # raises NotImplementedError

    elif method.upper() == "RASMHA":
        result = rasmha(system)

    else:
        raise ValueError("method must be 'RASMHA' or 'OPTA'")

    execute_decisions(result.assignments)
    transmit_results_to_av()

    return result


