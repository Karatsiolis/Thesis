def dist(p1, p2) -> float:
    """Euclidean distance in SUMO coordinates (m)."""
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])


def find_edge(net, lon: float, lat: float, radius: float = 30):
    """
    Finds the nearest road (edge) for a passenger vehicle around a lon/lat
    point. The search radius is doubled up to 500 m.
    """
    x, y = net.convertLonLat2XY(lon, lat)
    r = radius

    while r <= 500:
        neighbors = net.getNeighboringEdges(x, y, r)

        drivable = [
            (edge, d) for edge, d in neighbors
            if not edge.isSpecial() and edge.allows("passenger")
        ]

        if drivable:
            edge, _ = min(drivable, key=lambda item: item[1])
            return edge

        r *= 2

    raise RuntimeError(f"Δεν βρέθηκε drivable edge κοντά στο ({lat}, {lon})")


def upload_delay(subtask: SubTask, R_av_bs: float) -> float:
    # Sending the input data from the AV to the BS
    return subtask.D_in / R_av_bs


def mec_compute_delay(subtask: SubTask, server: MECServer) -> float:
    # Computation on the MEC
    return subtask.omega / server.f_alloc


def return_delay(subtask: SubTask, R_av_bs: float) -> float:
    # Returning the result from the BS to the AV
    return subtask.D_out / R_av_bs


def total_subtask_delay(
    subtask: SubTask,
    server: MECServer,
    R_av_bs: float,
) -> Tuple[float, float, float, float]:
    """Total subtask delay on a MEC: (total, upload, computation, return)."""
    u = upload_delay(subtask, R_av_bs)
    c = mec_compute_delay(subtask, server)
    r = return_delay(subtask, R_av_bs)
    return u + c + r, u, c, r


def get_next_subtask(task: Task, next_order: int) -> Optional[SubTask]:
    # The subtask with the requested order (None if there is no other)
    for st in task.subtasks:
        if st.order == next_order:
            return st
    return None


def create_task_from_template(template: TaskTemplate, current_time: float) -> Task:
    """
    Creates the actual Task from a template. The relative deadlines
    become absolute simulation times.
    """
    subtasks: List[SubTask] = []

    for spec in template.subtasks:
        subtasks.append(
            SubTask(
                subtask_id=spec.subtask_id,
                parent_task_id=template.task_id,
                D_in=spec.D_in,
                D_out=spec.D_out,
                omega=spec.omega,
                deadline=current_time + spec.relative_deadline,
                order=spec.order,
                earliest_start=current_time + spec.earliest_offset,
            )
        )

    return Task(
        task_id=template.task_id,
        av_id=template.av_id,
        subtasks=subtasks,
        tau=template.tau,
        generated_at=current_time,
    )


