def build_route_polyline(net, edge_ids: List[str]) -> List[Tuple[float, float]]:
    """Polyline of the route built from the shapes of the SUMO edges (in m)."""
    points: List[Tuple[float, float]] = []

    for edge_id in edge_ids:
        edge = net.getEdge(edge_id)
        shape = edge.getShape()

        if not shape:
            continue

        for p in shape:
            point = (float(p[0]), float(p[1]))

            # Skip duplicate consecutive points
            if not points or dist(points[-1], point) > 1e-6:
                points.append(point)

    if len(points) < 2:
        raise RuntimeError("Η διαδρομή δεν έχει αρκετά σημεία για polyline.")

    return points


def distance_point_to_segment(
    point: Tuple[float, float],
    seg_a: Tuple[float, float],
    seg_b: Tuple[float, float],
) -> float:
    """Distance of a point from a line segment."""
    px, py = point
    ax, ay = seg_a
    bx, by = seg_b

    abx = bx - ax
    aby = by - ay

    apx = px - ax
    apy = py - ay

    ab_len_sq = abx * abx + aby * aby

    if ab_len_sq == 0:
        return dist(point, seg_a)

    # Projection of the point onto the segment, clamped to [0, 1]
    t = (apx * abx + apy * aby) / ab_len_sq
    t = max(0.0, min(1.0, t))

    closest = (
        ax + t * abx,
        ay + t * aby,
    )

    return dist(point, closest)


def route_passes_near_bs(
    route_polyline: List[Tuple[float, float]],
    bs_pos: Tuple[float, float],
    coverage_radius: float,
) -> bool:
    """True if the route passes through the coverage of the BS (geometric check only)."""
    for i in range(1, len(route_polyline)):
        segment_start = route_polyline[i - 1]
        segment_end = route_polyline[i]

        d = distance_point_to_segment(
            point=bs_pos,
            seg_a=segment_start,
            seg_b=segment_end,
        )

        if d <= coverage_radius:
            return True

    return False


def route_cumulative_distances(
    route_polyline: List[Tuple[float, float]],
) -> List[float]:
    """
    Distance of each route point from the start of the route.
    Used for ordering the MECs, not for predicting times.
    """
    cumulative = [0.0]

    for i in range(1, len(route_polyline)):
        cumulative.append(
            cumulative[-1] + dist(route_polyline[i - 1], route_polyline[i])
        )

    return cumulative


def closest_route_distance_to_bs(
    route_polyline: List[Tuple[float, float]],
    bs_pos: Tuple[float, float],
) -> Tuple[float, float]:
    """
    Returns the minimum BS-route distance and the point of the route
    (as distance from the start) where it occurs.
    Used for ordering the MECs, not for predicting times.
    """
    cumulative = route_cumulative_distances(route_polyline)

    best_distance = inf
    best_route_distance = inf

    # For each segment: projection of the BS onto the segment
    for i in range(1, len(route_polyline)):
        seg_a = route_polyline[i - 1]
        seg_b = route_polyline[i]

        ax, ay = seg_a
        bx, by = seg_b
        px, py = bs_pos

        abx = bx - ax
        aby = by - ay
        ab_len_sq = abx * abx + aby * aby

        if ab_len_sq == 0.0:
            d = dist(bs_pos, seg_a)
            route_d = cumulative[i - 1]
        else:
            t = ((px - ax) * abx + (py - ay) * aby) / ab_len_sq
            t = max(0.0, min(1.0, t))

            closest = (
                ax + t * abx,
                ay + t * aby,
            )

            d = dist(bs_pos, closest)
            route_d = cumulative[i - 1] + t * dist(seg_a, seg_b)

        # Keep the nearest point
        if d < best_distance:
            best_distance = d
            best_route_distance = route_d

    return best_distance, best_route_distance


def compute_route_mec_candidates(
    route_polyline: List[Tuple[float, float]],
    bs_xy: Dict[int, Tuple[float, float]],
    coverage_radius: float,
) -> List[int]:
    """
    The BS/MECs that cover the AV's route, in the order the AV will meet
    them. Coverage entry/exit times are not predicted.
    """
    candidates_with_route_distance: List[Tuple[float, int]] = []

    for bs_id, bs_pos in bs_xy.items():
        min_distance, route_distance = closest_route_distance_to_bs(
            route_polyline=route_polyline,
            bs_pos=bs_pos,
        )

        if min_distance <= coverage_radius:
            candidates_with_route_distance.append((route_distance, bs_id))

    # Sort by position along the route
    candidates_with_route_distance.sort()

    return [bs_id for _, bs_id in candidates_with_route_distance]


#------------------------------------------------------------
#Route-aware target MEC selection
#------------------------------------------------------------

def av_route_distance(
    av_pos: Tuple[float, float],
    route_polyline: List[Tuple[float, float]],
) -> float:
    """Position of the AV on the route, as distance from its start."""
    cumulative = route_cumulative_distances(route_polyline)
    best_route_dist = 0.0
    best_geom_dist = inf

    # Projection of the AV onto the nearest segment of the route
    for i in range(1, len(route_polyline)):
        ax, ay = route_polyline[i - 1]
        bx, by = route_polyline[i]
        px, py = av_pos
        abx, aby = bx - ax, by - ay
        ab_len_sq = abx * abx + aby * aby

        if ab_len_sq == 0.0:
            t = 0.0
        else:
            t = ((px - ax) * abx + (py - ay) * aby) / ab_len_sq
            t = max(0.0, min(1.0, t))

        closest = (ax + t * abx, ay + t * aby)
        geom_dist = dist(av_pos, closest)

        if geom_dist < best_geom_dist:
            best_geom_dist = geom_dist
            best_route_dist = cumulative[i - 1] + t * dist(route_polyline[i - 1], route_polyline[i])

    return best_route_dist


def choose_route_aware_target_mec(
    task: Task,
    subtask: SubTask,
    current_time: float,
    route_candidates: List[int],
    passed_bs: set[int],
    state: OnlineState,
    current_av_pos: Tuple[float, float],
    route_polyline: List[Tuple[float, float]],
    avg_speed: float,
    bs_xy: Dict[int, Tuple[float, float]],
    real_reachable_bs: List[int],
    dependency_ready_time: float,
) -> Optional[int]:
    """
    Core of RASMHA: chooses the target MEC for a ready subtask.

    For each MEC on the route that has not been passed, it estimates when the
    subtask would finish there (arrival in coverage + execution delay).
    MECs that do not meet deadline/tau are rejected and the one with the
    earliest estimated completion is chosen. No capacity is reserved here.
    """
    current_av_dist = av_route_distance(current_av_pos, route_polyline)

    best_bs: Optional[int] = None
    best_estimated_finish = inf

    for bs_id in route_candidates:
        if bs_id in passed_bs:
            continue

        server = SERVERS[bs_id]
        delay, _, _, _ = total_subtask_delay(subtask, server, V2I_RATE)

        # Estimated arrival in coverage: now, if the AV is already inside;
        # otherwise distance to the entry point / average speed. The entry
        # point is taken as the route point closest to the BS minus the
        # coverage radius.
        if bs_id in real_reachable_bs:
            estimated_arrival = current_time
        else:
            _, bs_route_dist = closest_route_distance_to_bs(route_polyline, bs_xy[bs_id])
            bs_entry_dist = max(current_av_dist, bs_route_dist - BS_COVERAGE_M)
            remaining_dist = max(0.0, bs_entry_dist - current_av_dist)
            estimated_arrival = current_time + remaining_dist / avg_speed

        # Execution starts when the AV arrives and the previous subtask has finished
        estimated_start = max(estimated_arrival, dependency_ready_time)
        estimated_finish = estimated_start + delay

        # Reject MECs that do not meet the subtask deadline or the total tau
        if estimated_finish > subtask.deadline:
            continue

        if estimated_finish > task.generated_at + task.tau:
            continue

        # Keep the MEC with the earliest estimated completion
        if estimated_finish < best_estimated_finish:
            best_estimated_finish = estimated_finish
            best_bs = bs_id

    return best_bs


def create_job_for_target_mec(
    task: Task,
    subtask: SubTask,
    current_time: float,
    target_bs: int,
    state: OnlineState,
) -> Optional[ScheduledJob]:
    """
    Creates a ScheduledJob when the AV is already inside the target MEC's
    coverage. This is where the actual capacity, deadline and total tau
    checks are made, using the current time. Returns None if any check fails.
    """
    server = SERVERS[target_bs]

    # The MEC is full
    if state.mec_load.get(target_bs, 0) >= server.C_max:
        return None

    delay, u, c, r = total_subtask_delay(subtask, server, V2I_RATE)

    # Start no earlier than earliest_start and the finish of the previous subtask
    t_start = max(
        current_time,
        subtask.earliest_start,
        state.last_finish.get(task.task_id, task.generated_at),
    )

    t_finish = t_start + delay

    # Check the subtask deadline and the total tau
    if t_finish > subtask.deadline:
        return None

    if t_finish > task.generated_at + task.tau:
        return None

    return ScheduledJob(
        task_id=task.task_id,
        subtask_id=subtask.subtask_id,
        av_id=task.av_id,
        bs_id=target_bs,
        start_time=t_start,
        finish_time=t_finish,
        delay=delay,
        upload_time=u,
        compute_time=c,
        return_time=r,
    )


def start_job(job: ScheduledJob, state: OnlineState) -> None:
    #Finalizes the assignment: the subtask starts and reserves a slot on the MEC
    key = (job.task_id, job.subtask_id)

    state.running_jobs.append(job)

    state.assignments[key] = job.bs_id
    state.D[key] = job.delay
    state.start_times[key] = job.start_time
    state.finish_times[key] = job.finish_time

    # Reserve a slot on the MEC
    state.mec_load[job.bs_id] = state.mec_load.get(job.bs_id, 0) + 1

    print(
        f"  t={job.start_time:.2f}s  "
        f"Task {job.task_id} / SubTask {job.subtask_id} από AV{job.av_id} "
        f"→ OFFLOAD στο BS{job.bs_id}"
    )

    print(
        f"            upload={job.upload_time:.4f}s | "
        f"compute={job.compute_time:.4f}s | "
        f"return={job.return_time:.4f}s | "
        f"finish={job.finish_time:.2f}s | "
        f"delay={job.delay:.4f}s"
    )


def recover_subtask_after_coverage_exit(
    job: ScheduledJob,
    current_time: float,
    state: OnlineState,
) -> None:
    """
    Recovery mechanism: when the AV leaves the MEC coverage before the
    result is returned, only the current attempt is cancelled.

    next_order and last_finish are not changed, so the same subtask stays
    ready and a new MEC is chosen among the next ones on the route.
    No intermediate state is transferred: the subtask starts from the beginning.
    """
    task = state.active_tasks.get(job.task_id)

    if task is None:
        return

    if job.task_id in state.completed_tasks or job.task_id in state.failed_tasks:
        return

    key = (job.task_id, job.subtask_id)

    # If the job is still running, it is cancelled and the MEC slot is freed
    if job in state.running_jobs:
        state.running_jobs.remove(job)
        state.mec_load[job.bs_id] = max(
            0,
            state.mec_load.get(job.bs_id, 0) - 1,
        )

    # Only the data of the failed attempt is removed;
    # the subtask is not marked as failed
    state.target_mec.pop(key, None)
    state.assignments.pop(key, None)
    state.D.pop(key, None)
    state.start_times.pop(key, None)
    state.finish_times.pop(key, None)
    state.last_wait_log.pop(key, None)

    print(
        f"  t={current_time:.2f}s  "
        f"RECOVERY: Task {job.task_id} / SubTask {job.subtask_id} από AV{job.av_id} "
        f"ακυρώθηκε στο BS{job.bs_id}, επειδή το AV βγήκε από την κάλυψη. "
        f"Θα επιλεγεί επόμενος MEC και το subtask θα ξεκινήσει από την αρχή."
    )


def complete_finished_jobs(
    current_time: float,
    state: OnlineState,
    bs_xy: Dict[int, Tuple[float, float]],
) -> None:
    """
    Completes the subtasks with finish_time <= current time. The result is
    considered returned only if the AV is still inside the coverage of the
    same BS/MEC; otherwise recovery is triggered.
    """
    for job in list(state.running_jobs):
        if job.finish_time <= current_time:
            # The job has finished: free the MEC slot
            state.running_jobs.remove(job)

            state.mec_load[job.bs_id] = max(
                0,
                state.mec_load.get(job.bs_id, 0) - 1,
            )

            task = state.active_tasks[job.task_id]
            veh_id = f"av{job.av_id}"

            # If the AV no longer exists in SUMO, it cannot receive the result
            if veh_id not in traci.vehicle.getIDList():
                fail_task(
                    task,
                    state,
                    reason=(
                        f"το AV{job.av_id} δεν υπάρχει πλέον στο SUMO, "
                        f"άρα δεν μπορεί να επιστραφεί το αποτέλεσμα"
                    ),
                )
                continue

            # Check actual coverage at the moment the result is returned
            current_pos = traci.vehicle.getPosition(veh_id)
            bs_pos = bs_xy[job.bs_id]

            if dist(current_pos, bs_pos) > BS_COVERAGE_M:
                # The AV is out of coverage: recovery of the same subtask
                # (the job and the MEC slot have already been released above)
                recover_subtask_after_coverage_exit(
                    job=job,
                    current_time=current_time,
                    state=state,
                )
                continue

            # Success: move on to the next subtask
            key = (job.task_id, job.subtask_id)

            state.last_finish[job.task_id] = job.finish_time
            state.next_order[job.task_id] += 1

            print(
                f"  t={current_time:.2f}s  "
                f"Task {job.task_id} / SubTask {job.subtask_id} "
                f"υπολογίστηκε στο BS{job.bs_id} και το αποτέλεσμα επιστράφηκε στο AV{job.av_id}"
            )

            # If there is no next subtask, the task is complete
            next_st = get_next_subtask(task, state.next_order[job.task_id])

            if next_st is None:
                total_delay = job.finish_time - task.generated_at

                state.task_delays[task.task_id] = total_delay
                state.completed_tasks.add(task.task_id)

                print(
                    f"  t={current_time:.2f}s  "
                    f"Task {task.task_id} ΟΛΟΚΛΗΡΩΘΗΚΕ | "
                    f"total_delay={total_delay:.4f}s"
                )


def fail_task(task: Task, state: OnlineState, reason: str) -> None:
    """
    Marks the task as failed: cancels its target MECs and running jobs,
    frees the MEC slots and records the remaining subtasks as failed.
    """
    if task.task_id in state.failed_tasks or task.task_id in state.completed_tasks:
        return

    state.failed_tasks.add(task.task_id)

    # Remove the waiting target MECs
    for key, target_bs in list(state.target_mec.items()):
        if key[0] == task.task_id:
            state.target_mec.pop(key, None)

    # Cancel running jobs and free the MEC slot
    for job in list(state.running_jobs):
        if job.task_id == task.task_id:
            state.running_jobs.remove(job)
            state.mec_load[job.bs_id] = max(
                0,
                state.mec_load.get(job.bs_id, 0) - 1,
            )

    # The current and following subtasks without an assignment are recorded as failed
    current_order = state.next_order.get(task.task_id, 0)

    for st in sorted(task.subtasks, key=lambda s: s.order):
        if st.order >= current_order:
            key = (task.task_id, st.subtask_id)
            if key not in state.assignments and key not in state.failed_subtasks:
                state.failed_subtasks.append(key)

    print(
        f"  Task {task.task_id} από AV{task.av_id} ΑΠΕΤΥΧΕ: {reason}"
    )


def prepare_sumo():
    """
    Reads the road network, starts SUMO, inserts the AVs and computes, for
    each AV, its route and the MECs it will meet (in order).
    Coverage times are not predicted.
    """
    net = sumolib.net.readNet(NET_FILE)

    # Convert BS positions from lon/lat to SUMO coordinates
    bs_xy = {
        bs_id: net.convertLonLat2XY(lon, lat)
        for bs_id, (lon, lat) in BS_COORDS.items()
    }

    # Start and end road of each AV from the config
    av_edges: Dict[int, Tuple[object, object]] = {}

    for av_id in sorted(VEHICLES.keys()):
        vehicle = VEHICLES[av_id]

        start_edge = find_edge(
            net,
            float(vehicle["start_lon"]),
            float(vehicle["start_lat"]),
        )

        end_edge = find_edge(
            net,
            float(vehicle["end_lon"]),
            float(vehicle["end_lat"]),
        )

        av_edges[av_id] = (start_edge, end_edge)

    # Start SUMO-GUI with a simulation step of 0.01 s
    traci.start(["sumo-gui", "-c", SUMOCFG, "--step-length", "0.01"])

    # Show the BSs as points in SUMO-GUI
    for bs_id, (x, y) in bs_xy.items():
        traci.poi.add(
            f"BS{bs_id}",
            x,
            y,
            color=(255, 0, 0, 220),
            layer=10,
            width=10,
            height=10,
        )

    route_mec_candidates_by_av: Dict[int, List[int]] = {}
    av_route_polylines: Dict[int, List[Tuple[float, float]]] = {}
    av_travel_times: Dict[int, float] = {}

    # For each AV: find the route, insert it into SUMO and compute the MEC candidates
    for av_id, (start_edge, end_edge) in av_edges.items():
        stage = traci.simulation.findRoute(
            start_edge.getID(),
            end_edge.getID(),
        )

        if not stage.edges:
            raise RuntimeError(f"Δεν βρέθηκε διαδρομή για AV {av_id}")

        route_id = f"route_av{av_id}"
        veh_id = f"av{av_id}"

        traci.route.add(route_id, stage.edges)

        traci.vehicle.add(
            veh_id,
            route_id,
            depart="now",
            departLane="best",
            departSpeed="0",
        )

        traci.vehicle.setColor(
            veh_id,
            get_vehicle_color(av_id),
        )

        # Route geometry and the MECs the AV will meet, in order
        route_polyline = build_route_polyline(net, list(stage.edges))

        route_candidates = compute_route_mec_candidates(
            route_polyline=route_polyline,
            bs_xy=bs_xy,
            coverage_radius=BS_COVERAGE_M,
        )

        route_mec_candidates_by_av[av_id] = route_candidates
        av_route_polylines[av_id] = route_polyline
        av_travel_times[av_id] = float(stage.travelTime)

        print(
            f"AV {av_id} inserted | "
            f"length={stage.length:.0f} m | "
            f"est. travel={stage.travelTime:.1f} s"
        )

        print(
            f"  Route MEC candidates for AV{av_id}: {route_candidates}"
        )

    return bs_xy, av_edges, route_mec_candidates_by_av, av_route_polylines, av_travel_times


#---------------------------------------------------------
#Main online simulation
#---------------------------------------------------------

def run_online_sumo_rasmha() -> OnlineState:
    """
    Unified online SUMO + RASMHA simulation. At each step: job completion,
    AV arrivals, coverage update (with recovery on exit), task generation
    and route-aware decisions for the ready subtasks.
    """
    print("── Online SUMO + Route-Aware Target MEC RASMHA simulation ───────────────────")

    bs_xy, av_edges, route_mec_candidates_by_av, av_route_polylines, av_travel_times = prepare_sumo()

    # Average speed of each AV = route length / estimated travel time
    av_avg_speeds: Dict[int, float] = {}
    for av_id, polyline in av_route_polylines.items():
        total_length = route_cumulative_distances(polyline)[-1]
        av_avg_speeds[av_id] = total_length / av_travel_times[av_id]

    state = OnlineState(
        mec_load={bs_id: 0 for bs_id in SERVERS}
    )

    generated_task_ids: set[int] = set()
    target_vehicles = {f"av{av_id}" for av_id in av_edges}

    # Whether each AV is inside each BS (to detect entry/exit)
    in_range: Dict[int, Dict[int, bool]] = {
        av_id: {bs_id: False for bs_id in BS_COORDS}
        for av_id in av_edges
    }

    # BSs each AV has already passed (once it actually leaves their coverage)
    passed_bs_by_av: Dict[int, set[int]] = {
        av_id: set()
        for av_id in av_edges
    }

    try:
        while traci.simulation.getTime() <= MAX_SIM_TIME:

            # Stop when all AVs have arrived, all tasks have been generated,
            # no job is running and no target MEC is waiting
            all_templates_generated = len(generated_task_ids) == len(TASK_TEMPLATES)

            if (
                not target_vehicles
                and all_templates_generated
                and not state.running_jobs
                and not state.target_mec
            ):
                break

            traci.simulationStep()
            t = traci.simulation.getTime()

            #----------------------------------------------------
            #1. Complete jobs that finished in this step
            #----------------------------------------------------
            complete_finished_jobs(t, state, bs_xy)

            #----------------------------------------------------
            #2. AV arrivals at their destination
            #----------------------------------------------------
            arrived = set(traci.simulation.getArrivedIDList())

            for veh_id in list(target_vehicles):
                if veh_id in arrived:
                    target_vehicles.remove(veh_id)
                    av_id = int(veh_id.replace("av", ""))

                    print(f"  t={t:.1f}s  {veh_id} έφτασε στον προορισμό")

                    # The unfinished tasks of the AV fail
                    for task in list(state.active_tasks.values()):
                        if (
                            task.av_id == av_id
                            and task.task_id not in state.completed_tasks
                            and task.task_id not in state.failed_tasks
                        ):
                            fail_task(
                                task,
                                state,
                                reason=f"το AV{av_id} έφτασε/έφυγε πριν επιστραφεί το αποτέλεσμα",
                            )

            #----------------------------------------------------
            #3. Current coverage of each AV and recovery on BS exit
            #----------------------------------------------------
            current_reachable: Dict[int, List[int]] = {
                av_id: [] for av_id in av_edges
            }

            av_positions: Dict[int, Tuple[float, float]] = {}

            for av_id in av_edges:
                veh_id = f"av{av_id}"

                if veh_id not in traci.vehicle.getIDList():
                    continue

                pos = traci.vehicle.getPosition(veh_id)

                av_positions[av_id] = pos

                for bs_id, bs_pos in bs_xy.items():
                    inside = dist(pos, bs_pos) <= BS_COVERAGE_M

                    if inside:
                        current_reachable[av_id].append(bs_id)

                    # Entry into the BS coverage
                    if inside and not in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = True
                        print(f"  t={t:.1f}s  AV{av_id} → εντός BS{bs_id}")

                    # Exit from the coverage: the BS is now considered passed
                    elif not inside and in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = False
                        passed_bs_by_av[av_id].add(bs_id)
                        print(f"  t={t:.1f}s  AV{av_id} → εκτός  BS{bs_id}")

                        # Recovery for the AV's jobs running on the BS
                        # whose coverage it has just left
                        for job in list(state.running_jobs):
                            if job.av_id == av_id and job.bs_id == bs_id:
                                recover_subtask_after_coverage_exit(
                                    job=job,
                                    current_time=t,
                                    state=state,
                                )

            #----------------------------------------------------
            #4. Online task generation
            #----------------------------------------------------
            for template in TASK_TEMPLATES:
                if template.task_id in generated_task_ids:
                    continue

                if t >= template.generate_at:
                    av_id = template.av_id
                    veh_id = f"av{av_id}"

                    # The task is generated only if the AV still exists in SUMO
                    if veh_id in traci.vehicle.getIDList():
                        task = create_task_from_template(template, t)

                        state.active_tasks[task.task_id] = task
                        state.next_order[task.task_id] = 0
                        state.last_finish[task.task_id] = task.generated_at
                        generated_task_ids.add(task.task_id)

                        print(
                            f"\n  t={t:.1f}s  Δημιουργήθηκε Task {task.task_id} από AV{task.av_id}"
                        )

                        for st in sorted(task.subtasks, key=lambda s: s.order):
                            print(
                                f"            SubTask {st.subtask_id}: "
                                f"D_in={st.D_in:.1e} bits | "
                                f"omega={st.omega:.1e} cycles | "
                                f"deadline={st.deadline:.1f}s"
                            )

                    else:
                        generated_task_ids.add(template.task_id)
                        print(
                            f"  t={t:.1f}s  Task {template.task_id} δεν δημιουργήθηκε "
                            f"γιατί το AV{template.av_id} δεν υπάρχει πλέον"
                        )

            #----------------------------------------------------
            #5. Route-aware decisions for the ready subtasks
            #----------------------------------------------------
            for task_id, task in list(state.active_tasks.items()):

                if task_id in state.completed_tasks or task_id in state.failed_tasks:
                    continue

                # A subtask of this task is already running: wait
                if any(job.task_id == task_id for job in state.running_jobs):
                    continue

                next_order = state.next_order[task_id]
                subtask = get_next_subtask(task, next_order)

                if subtask is None:
                    continue

                # The subtask is not ready in time yet
                if t < subtask.earliest_start:
                    continue

                # The previous subtask has not finished
                if t < state.last_finish.get(task_id, task.generated_at):
                    continue

                # The deadline passed before an assignment was made
                if t > subtask.deadline:
                    fail_task(
                        task,
                        state,
                        reason=f"χάθηκε το deadline του SubTask {subtask.subtask_id}",
                    )
                    continue

                av_id = task.av_id
                key = (task.task_id, subtask.subtask_id)

                route_candidates = route_mec_candidates_by_av.get(av_id, [])
                real_reachable_bs = current_reachable.get(av_id, [])
                passed_bs = passed_bs_by_av.get(av_id, set())

                # If the target was passed without an offload,
                # it is removed so that a new MEC is chosen
                target_bs = state.target_mec.get(key)

                if (
                    target_bs is not None
                    and target_bs in passed_bs
                    and target_bs not in real_reachable_bs
                ):
                    state.target_mec.pop(key, None)
                    print(
                        f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id}: "
                        f"το target BS{target_bs} προσπεράστηκε χωρίς offload"
                    )
                    target_bs = None

                # Choose a target MEC, if there is none yet
                if target_bs is None:
                    target_bs = choose_route_aware_target_mec(
                        task=task,
                        subtask=subtask,
                        current_time=t,
                        route_candidates=route_candidates,
                        passed_bs=passed_bs,
                        state=state,
                        current_av_pos=av_positions.get(av_id, (0.0, 0.0)),
                        route_polyline=av_route_polylines[av_id],
                        avg_speed=av_avg_speeds[av_id],
                        bs_xy=bs_xy,
                        real_reachable_bs=real_reachable_bs,
                        dependency_ready_time=state.last_finish.get(task_id, task.generated_at),
                    )

                    # No feasible MEC on the route: the task fails
                    if target_bs is None:
                        fail_task(
                            task,
                            state,
                            reason=(
                                f"δεν υπάρχει εφικτός μη προσπερασμένος MEC "
                                f"για το SubTask {subtask.subtask_id}"
                            ),
                        )
                        continue

                    state.target_mec[key] = target_bs

                    print(
                        f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                        f"επέλεξε target BS{target_bs} από route candidates {route_candidates}"
                    )

                # The AV is not yet inside the target's coverage: wait
                if target_bs not in real_reachable_bs:
                    last_log = state.last_wait_log.get(key, -inf)

                    if t - last_log >= WAIT_LOG_PERIOD:
                        state.last_wait_log[key] = t

                        remaining = [
                            bs_id for bs_id in route_candidates
                            if bs_id not in passed_bs
                        ]

                        print(
                            f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                            f"περιμένει target BS{target_bs} | "
                            f"current_range={real_reachable_bs} | "
                            f"remaining_route_mecs={remaining}"
                        )

                    continue

                # The AV is inside the target's coverage: check capacity,
                # deadline and tau, and start if feasible
                job = create_job_for_target_mec(
                    task=task,
                    subtask=subtask,
                    current_time=t,
                    target_bs=target_bs,
                    state=state,
                )

                if job is not None:
                    state.target_mec.pop(key, None)
                    start_job(job, state)
                    continue

                # The MEC is full: wait as long as deadline/tau can still be met,
                # otherwise fail
                server = SERVERS[target_bs]
                delay, _, _, _ = total_subtask_delay(subtask, server, V2I_RATE)

                if state.mec_load.get(target_bs, 0) >= server.C_max:
                    if t + delay > subtask.deadline or t + delay > task.generated_at + task.tau:
                        fail_task(
                            task,
                            state,
                            reason=(
                                f"δεν υπήρχε capacity στο target BS{target_bs} "
                                f"πριν το deadline/tau του SubTask {subtask.subtask_id}"
                            ),
                        )
                        continue

                    last_log = state.last_wait_log.get(key, -inf)

                    if t - last_log >= WAIT_LOG_PERIOD:
                        state.last_wait_log[key] = t
                        print(
                            f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                            f"είναι σε range του target BS{target_bs}, αλλά περιμένει capacity"
                        )

                    continue

                # Capacity is available but deadline/tau can no longer be met: fail
                fail_task(
                    task,
                    state,
                    reason=(
                        f"το SubTask {subtask.subtask_id} δεν προλαβαίνει πλέον "
                        f"deadline/tau με target BS{target_bs}"
                    ),
                )

        # End of simulation: anything not completed is considered failed
        for task in list(state.active_tasks.values()):
            if (
                task.task_id not in state.completed_tasks
                and task.task_id not in state.failed_tasks
            ):
                fail_task(
                    task,
                    state,
                    reason="τέλος προσομοίωσης χωρίς ολοκλήρωση",
                )

    finally:
        traci.close()

    return state


