@dataclass
class SubTask:
    """
    Part of a task that is executed entirely on one MEC via V2I.
    Subtask s+1 starts only after subtask s has completed.
    """
    subtask_id: int
    parent_task_id: int
    D_in: float              # input data size (bits)
    D_out: float             # result size (bits)
    omega: float             # required CPU cycles
    deadline: float          # absolute deadline in SUMO time
    order: int               # execution order within the task
    earliest_start: float    # earliest absolute start time


@dataclass
class Task:
    """Task generated by an autonomous vehicle (AV)."""
    task_id: int
    av_id: int
    subtasks: List[SubTask]
    tau: float               # maximum total delay, relative to generated_at
    generated_at: float      # generation time


@dataclass
class MECServer:
    """MEC server co-located with the BS/RSU."""
    bs_id: int
    F_total: float           # total CPU frequency
    C_max: int               # maximum number of concurrent subtasks

    @property
    def f_alloc(self) -> float:
        # Each subtask gets an equal share of the CPU: F_total / C_max
        if self.C_max <= 0:
            raise ValueError(f"C_max must be > 0 for BS {self.bs_id}")
        return self.F_total / self.C_max


@dataclass
class SubTaskSpec:
    """
    Subtask template before it is created in the simulation.
    Deadline and earliest start are relative to the task generation time.
    """
    subtask_id: int
    D_in: float
    D_out: float
    omega: float
    relative_deadline: float
    order: int
    earliest_offset: float = 0.0


@dataclass
class TaskTemplate:
    """Task template that is created online at a given simulation time."""
    task_id: int
    av_id: int
    generate_at: float
    tau: float
    subtasks: List[SubTaskSpec]


@dataclass
class ScheduledJob:
    """
    Subtask running on a MEC.
    finish_time = start + upload + computation + return of the result to the AV.
    """
    task_id: int
    subtask_id: int
    av_id: int
    bs_id: int
    start_time: float
    finish_time: float
    delay: float
    upload_time: float
    compute_time: float
    return_time: float


@dataclass
class OnlineState:
    """State of the online simulation."""
    active_tasks: Dict[int, Task] = field(default_factory=dict)
    completed_tasks: set[int] = field(default_factory=set)
    failed_tasks: set[int] = field(default_factory=set)

    # Sequential execution: next subtask and finish time of the previous one
    next_order: Dict[int, int] = field(default_factory=dict)
    last_finish: Dict[int, float] = field(default_factory=dict)

    # Subtasks currently running on a MEC
    running_jobs: List[ScheduledJob] = field(default_factory=list)

    # Target MEC chosen for a ready subtask, while the AV
    # has not yet entered its coverage
    target_mec: Dict[Tuple[int, int], int] = field(default_factory=dict)

    # Assignment, delay and times of each subtask (key: task_id, subtask_id)
    assignments: Dict[Tuple[int, int], int] = field(default_factory=dict)
    D: Dict[Tuple[int, int], float] = field(default_factory=dict)
    start_times: Dict[Tuple[int, int], float] = field(default_factory=dict)
    finish_times: Dict[Tuple[int, int], float] = field(default_factory=dict)

    task_delays: Dict[int, float] = field(default_factory=dict)
    failed_subtasks: List[Tuple[int, int]] = field(default_factory=list)

    # Current number of subtasks on each MEC (capacity check)
    mec_load: Dict[int, int] = field(default_factory=dict)

    # So that waiting messages are not printed at every step
    last_wait_log: Dict[Tuple[int, int], float] = field(default_factory=dict)


