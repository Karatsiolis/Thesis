"""
online_sumo_rasmha.py
=====================

Online SUMO + Route-Aware Target MEC RASMHA integration για τη διπλωματική.

Λογική:
  - V2I only
  - MEC-only execution
  - no caching
  - no task-state migration
  - recovery με ακύρωση και επανεκτέλεση του ίδιου subtask στον επόμενο MEC
  - no energy
  - specific SUMO route
  - sequential subtasks
  - route-aware target MEC selection χωρίς predicted coverage times

Σημαντικό:
  - Το AV γνωρίζει τη διαδρομή του.
  - Από τη route υπολογίζεται η διατεταγμένη λίστα MEC/BS που θα συναντήσει.
  - Δεν προβλέπονται enter/exit coverage times.
  - Για κάθε ready subtask επιλέγεται target MEC από τους μη προσπερασμένους
    MEC servers της route.
  - Το AV περιμένει μέχρι να μπει πραγματικά σε range του target MEC.
  - Μόλις μπει σε range, γίνεται offload αν υπάρχει capacity και προλαβαίνει
    deadline/tau.
  - Αν το AV βγει πραγματικά από την κάλυψη ενώ εκτελείται subtask,
    το job ακυρώνεται, ο MEC πόρος απελευθερώνεται και το ίδιο subtask
    επανέρχεται για επιλογή επόμενου MEC της route.
  - Το αποτέλεσμα θεωρείται επιτυχές μόνο αν, στο πραγματικό finish_time,
    το AV βρίσκεται ακόμα στην κάλυψη του ίδιου BS/MEC.
"""

