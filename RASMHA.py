def run_online_sumo_rasmha() -> OnlineState:
    """
    Ενιαία online προσομοίωση SUMO + Route-Aware Target MEC RASMHA.

    Χωρίς predicted coverage windows:
      - το AV ξέρει τη route και τη σειρά των MEC servers,
      - κάθε ready subtask παίρνει target MEC,
      - το AV περιμένει να μπει πραγματικά στο range του target MEC,
      - τότε γίνεται offload αν υπάρχει capacity και τηρούνται deadline/tau,
      - αν βγει πραγματικά από την κάλυψη κατά την εκτέλεση, γίνεται recovery
        με ακύρωση και επανεκτέλεση του ίδιου subtask στον επόμενο MEC.
    """
    print("── Online SUMO + Route-Aware Target MEC RASMHA simulation ───────────────────")

    bs_xy, av_edges, route_mec_candidates_by_av, av_route_polylines, av_travel_times = prepare_sumo()

    av_avg_speeds: Dict[int, float] = {}
    for av_id, polyline in av_route_polylines.items():
        total_length = route_cumulative_distances(polyline)[-1]
        av_avg_speeds[av_id] = total_length / av_travel_times[av_id]

    state = OnlineState(
        mec_load={bs_id: 0 for bs_id in SERVERS}
    )

    generated_task_ids: set[int] = set()
    target_vehicles = {f"av{av_id}" for av_id in av_edges}

    # Coverage state για enter/exit logs.
    in_range: Dict[int, Dict[int, bool]] = {
        av_id: {bs_id: False for bs_id in BS_COORDS}
        for av_id in av_edges
    }

    # BS που έχουν ήδη προσπεραστεί από κάθε AV.
    # Ένας BS θεωρείται προσπερασμένος όταν το AV βγει πραγματικά από το range του.
    passed_bs_by_av: Dict[int, set[int]] = {
        av_id: set()
        for av_id in av_edges
    }

    try:
        while traci.simulation.getTime() <= MAX_SIM_TIME:

            # Stop condition:
            # Όλα τα AV έφτασαν, όλα τα tasks δημιουργήθηκαν, δεν τρέχει job,
            # και δεν υπάρχει pending target MEC.
            all_templates_generated = len(generated_task_ids) == len(TASK_TEMPLATES)

            if (
                not target_vehicles
                and all_templates_generated
                and not state.running_jobs
                and not state.target_mec
            ):
                break

            traci.simulationStep()
            t = traci.simulation.getTime()

            # ----------------------------------------------------
            # 1. Ολοκλήρωση jobs που τελείωσαν σε αυτό το time
            # ----------------------------------------------------
            complete_finished_jobs(t, state, bs_xy)

            # ----------------------------------------------------
            # 2. Έλεγχος αφίξεων AV
            # ----------------------------------------------------
            arrived = set(traci.simulation.getArrivedIDList())

            for veh_id in list(target_vehicles):
                if veh_id in arrived:
                    target_vehicles.remove(veh_id)
                    av_id = int(veh_id.replace("av", ""))

                    print(f"  t={t:.1f}s  {veh_id} έφτασε στον προορισμό")

                    # Αν υπάρχουν tasks αυτού του AV που δεν ολοκληρώθηκαν, θα αποτύχουν.
                    for task in list(state.active_tasks.values()):
                        if (
                            task.av_id == av_id
                            and task.task_id not in state.completed_tasks
                            and task.task_id not in state.failed_tasks
                        ):
                            fail_task(
                                task,
                                state,
                                reason=f"το AV{av_id} έφτασε/έφυγε πριν επιστραφεί το αποτέλεσμα",
                            )

            # ----------------------------------------------------
            # 3. Current real coverage ανά AV/BS
            # ----------------------------------------------------
            current_reachable: Dict[int, List[int]] = {
                av_id: [] for av_id in av_edges
            }
            
            av_positions: Dict[int, Tuple[float, float]] = {}

            for av_id in av_edges:
                veh_id = f"av{av_id}"

                if veh_id not in traci.vehicle.getIDList():
                    continue

                pos = traci.vehicle.getPosition(veh_id)

                av_positions[av_id] = pos

                for bs_id, bs_pos in bs_xy.items():
                    inside = dist(pos, bs_pos) <= BS_COVERAGE_M

                    if inside:
                        current_reachable[av_id].append(bs_id)

                    # Enter event
                    if inside and not in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = True
                        print(f"  t={t:.1f}s  AV{av_id} → εντός BS{bs_id}")

                    # Exit event
                    elif not inside and in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = False
                        passed_bs_by_av[av_id].add(bs_id)
                        print(f"  t={t:.1f}s  AV{av_id} → εκτός  BS{bs_id}")

                        # Recovery μόνο για jobs που εκτελούνται αυτή τη στιγμή
                        # στον MEC από την κάλυψη του οποίου βγήκε το AV.
                        for job in list(state.running_jobs):
                            if job.av_id == av_id and job.bs_id == bs_id:
                                recover_subtask_after_coverage_exit(
                                    job=job,
                                    current_time=t,
                                    state=state,
                                )

            # ----------------------------------------------------
            # 4. Online task generation
            # ----------------------------------------------------
            for template in TASK_TEMPLATES:
                if template.task_id in generated_task_ids:
                    continue

                if t >= template.generate_at:
                    av_id = template.av_id
                    veh_id = f"av{av_id}"

                    # Δημιουργούμε task μόνο αν το AV υπάρχει ακόμα στο SUMO.
                    if veh_id in traci.vehicle.getIDList():
                        task = create_task_from_template(template, t)

                        state.active_tasks[task.task_id] = task
                        state.next_order[task.task_id] = 0
                        state.last_finish[task.task_id] = task.generated_at
                        generated_task_ids.add(task.task_id)

                        print(
                            f"\n  t={t:.1f}s  Δημιουργήθηκε Task {task.task_id} από AV{task.av_id}"
                        )

                        for st in sorted(task.subtasks, key=lambda s: s.order):
                            print(
                                f"            SubTask {st.subtask_id}: "
                                f"D_in={st.D_in:.1e} bits | "
                                f"omega={st.omega:.1e} cycles | "
                                f"deadline={st.deadline:.1f}s"
                            )

                    else:
                        generated_task_ids.add(template.task_id)
                        print(
                            f"  t={t:.1f}s  Task {template.task_id} δεν δημιουργήθηκε "
                            f"γιατί το AV{template.av_id} δεν υπάρχει πλέον"
                        )

            # ----------------------------------------------------
            # 5. Route-aware target MEC decisions για έτοιμα subtasks
            # ----------------------------------------------------
            for task_id, task in list(state.active_tasks.items()):

                if task_id in state.completed_tasks or task_id in state.failed_tasks:
                    continue

                # Αν ήδη τρέχει subtask αυτού του task, περιμένουμε.
                if any(job.task_id == task_id for job in state.running_jobs):
                    continue

                next_order = state.next_order[task_id]
                subtask = get_next_subtask(task, next_order)

                if subtask is None:
                    continue

                # Δεν είναι ακόμα έτοιμο χρονικά.
                if t < subtask.earliest_start:
                    continue

                # Το προηγούμενο subtask δεν έχει τελειώσει.
                if t < state.last_finish.get(task_id, task.generated_at):
                    continue

                # Αν πέρασε το deadline χωρίς assignment.
                if t > subtask.deadline:
                    fail_task(
                        task,
                        state,
                        reason=f"χάθηκε το deadline του SubTask {subtask.subtask_id}",
                    )
                    continue

                av_id = task.av_id
                key = (task.task_id, subtask.subtask_id)

                route_candidates = route_mec_candidates_by_av.get(av_id, [])
                real_reachable_bs = current_reachable.get(av_id, [])
                passed_bs = passed_bs_by_av.get(av_id, set())

                # Αν το προηγούμενο target έχει πλέον προσπεραστεί χωρίς να σταλεί,
                # το αφαιρούμε ώστε να επιλεγεί επόμενος κατάλληλος MEC.
                target_bs = state.target_mec.get(key)

                if (
                    target_bs is not None
                    and target_bs in passed_bs
                    and target_bs not in real_reachable_bs
                ):
                    state.target_mec.pop(key, None)
                    print(
                        f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id}: "
                        f"το target BS{target_bs} προσπεράστηκε χωρίς offload"
                    )
                    target_bs = None

                # Αν δεν υπάρχει target, επιλέγεται τώρα route-aware target MEC.
                if target_bs is None:
                    target_bs = choose_route_aware_target_mec(
                        task=task,
                        subtask=subtask,
                        current_time=t,
                        route_candidates=route_candidates,
                        passed_bs=passed_bs,
                        state=state,
                        current_av_pos=av_positions.get(av_id, (0.0, 0.0)),
                        route_polyline=av_route_polylines[av_id],
                        avg_speed=av_avg_speeds[av_id],
                        bs_xy=bs_xy,
                        real_reachable_bs=real_reachable_bs,
                        dependency_ready_time=state.last_finish.get(task_id, task.generated_at),
                    )

                    if target_bs is None:
                        fail_task(
                            task,
                            state,
                            reason=(
                                f"δεν υπάρχει εφικτός μη προσπερασμένος MEC "
                                f"για το SubTask {subtask.subtask_id}"
                            ),
                        )
                        continue

                    state.target_mec[key] = target_bs

                    print(
                        f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                        f"επέλεξε target BS{target_bs} από route candidates {route_candidates}"
                    )

                # Αν δεν είμαστε ακόμα σε πραγματικό range του target MEC, περιμένουμε.
                if target_bs not in real_reachable_bs:
                    last_log = state.last_wait_log.get(key, -inf)

                    if t - last_log >= WAIT_LOG_PERIOD:
                        state.last_wait_log[key] = t

                        remaining = [
                            bs_id for bs_id in route_candidates
                            if bs_id not in passed_bs
                        ]

                        print(
                            f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                            f"περιμένει target BS{target_bs} | "
                            f"current_range={real_reachable_bs} | "
                            f"remaining_route_mecs={remaining}"
                        )

                    continue

                # Είμαστε πραγματικά σε range του target MEC.
                # Ελέγχουμε capacity/deadline/tau και ξεκινάμε αν είναι εφικτό.
                job = create_job_for_target_mec(
                    task=task,
                    subtask=subtask,
                    current_time=t,
                    target_bs=target_bs,
                    state=state,
                )

                if job is not None:
                    state.target_mec.pop(key, None)
                    start_job(job, state)
                    continue

                # Αν δεν ξεκινάει λόγω capacity, περιμένουμε όσο υπάρχει περιθώριο.
                server = SERVERS[target_bs]
                delay, _, _, _ = total_subtask_delay(subtask, server, V2I_RATE)

                if state.mec_load.get(target_bs, 0) >= server.C_max:
                    if t + delay > subtask.deadline or t + delay > task.generated_at + task.tau:
                        fail_task(
                            task,
                            state,
                            reason=(
                                f"δεν υπήρχε capacity στο target BS{target_bs} "
                                f"πριν το deadline/tau του SubTask {subtask.subtask_id}"
                            ),
                        )
                        continue

                    last_log = state.last_wait_log.get(key, -inf)

                    if t - last_log >= WAIT_LOG_PERIOD:
                        state.last_wait_log[key] = t
                        print(
                            f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                            f"είναι σε range του target BS{target_bs}, αλλά περιμένει capacity"
                        )

                    continue

                # Αν υπάρχει capacity αλλά δεν προλαβαίνει πλέον deadline/tau, αποτυχία.
                fail_task(
                    task,
                    state,
                    reason=(
                        f"το SubTask {subtask.subtask_id} δεν προλαβαίνει πλέον "
                        f"deadline/tau με target BS{target_bs}"
                    ),
                )

        # Τέλος simulation: ό,τι έμεινε incomplete γίνεται failed.
        for task in list(state.active_tasks.values()):
            if (
                task.task_id not in state.completed_tasks
                and task.task_id not in state.failed_tasks
            ):
                fail_task(
                    task,
                    state,
                    reason="τέλος προσομοίωσης χωρίς ολοκλήρωση",
                )

    finally:
        traci.close()

    return state


# ============================================================
# Final report
# ============================================================

def print_final_report(state: OnlineState) -> None:
    """
    Τελική παρουσίαση αποτελεσμάτων στο terminal.

    Η συνάρτηση αλλάζει μόνο τον τρόπο εκτύπωσης και δεν επηρεάζει
    τη λειτουργία, τις αποφάσεις ή τα αποτελέσματα του αλγορίθμου.
    """
    report_width = 126

    print("\n" + "=" * report_width)
    print("RASMHA - FINAL SIMULATION REPORT".center(report_width))
    print("=" * report_width)

    if not state.active_tasks:
        print("Δεν δημιουργήθηκαν tasks.")
        return

    tasks = [
        state.active_tasks[task_id]
        for task_id in sorted(state.active_tasks)
    ]

    generated_tasks = len(tasks)
    generated_subtasks = sum(len(task.subtasks) for task in tasks)
    completed_tasks = sorted(state.completed_tasks)
    failed_tasks = sorted(state.failed_tasks)

    completed_count = len(completed_tasks)
    failed_count = len(failed_tasks)

    success_rate = (
        100.0 * completed_count / generated_tasks
        if generated_tasks > 0 else 0.0
    )
    failure_rate = (
        100.0 * failed_count / generated_tasks
        if generated_tasks > 0 else 0.0
    )

    completed_delays = sorted(
        state.task_delays[task_id]
        for task_id in completed_tasks
        if task_id in state.task_delays
    )

    total_completed_e2e = sum(completed_delays)
    mean_e2e = (
        total_completed_e2e / len(completed_delays)
        if completed_delays else 0.0
    )

    if completed_delays:
        n = len(completed_delays)
        middle = n // 2

        if n % 2 == 1:
            median_e2e = completed_delays[middle]
        else:
            median_e2e = (
                completed_delays[middle - 1]
                + completed_delays[middle]
            ) / 2.0

        min_e2e = completed_delays[0]
        max_e2e = completed_delays[-1]
    else:
        median_e2e = 0.0
        min_e2e = 0.0
        max_e2e = 0.0

    # --------------------------------------------------------
    # Simulation configuration
    # --------------------------------------------------------
    print("\nSIMULATION CONFIGURATION")
    print("-" * report_width)
    print(f"{'Vehicles':<34}: {len(VEHICLES)}")
    print(f"{'MEC Servers':<34}: {len(SERVERS)}")
    print(f"{'Generated Tasks':<34}: {generated_tasks}")
    print(f"{'Generated SubTasks':<34}: {generated_subtasks}")
    print(f"{'V2I Rate':<34}: {V2I_RATE / 1.0e6:.2f} Mbps")
    print(f"{'BS Coverage Radius':<34}: {BS_COVERAGE_M:.2f} m")

    # --------------------------------------------------------
    # Task-level results
    # --------------------------------------------------------
    print("\nTASK RESULTS")
    print("-" * report_width)

    header = (
        f"{'Task':>4}  "
        f"{'AV':>3}  "
        f"{'MEC Sequence':<18}  "
        f"{'Generated':>9}  "
        f"{'End/Fail':>9}  "
        f"{'Waiting':>9}  "
        f"{'Service':>9}  "
        f"{'E2E Delay':>10}  "
        f"{'Tau':>8}  "
        f"{'Status':<20}"
    )

    print(header)
    print("-" * report_width)

    for task in tasks:
        task_id = task.task_id

        ordered_subtasks = sorted(
            task.subtasks,
            key=lambda st: st.order,
        )

        assigned_bs = [
            state.assignments[(task_id, st.subtask_id)]
            for st in ordered_subtasks
            if (task_id, st.subtask_id) in state.assignments
        ]

        mec_sequence = (
            " -> ".join(str(bs_id) for bs_id in assigned_bs)
            if assigned_bs else "-"
        )

        service_time = sum(
            state.D.get((task_id, st.subtask_id), 0.0)
            for st in ordered_subtasks
        )

        task_finish_times = [
            state.finish_times[(task_id, st.subtask_id)]
            for st in ordered_subtasks
            if (task_id, st.subtask_id) in state.finish_times
        ]

        end_or_fail_time = (
            max(task_finish_times)
            if task_finish_times else None
        )

        if task_id in state.completed_tasks:
            e2e_delay = state.task_delays.get(task_id, inf)
            waiting_time = max(0.0, e2e_delay - service_time)

            status = (
                "COMPLETED"
                if e2e_delay <= task.tau
                else "TAU MISSED"
            )

            end_text = f"{end_or_fail_time:.2f}" if end_or_fail_time is not None else "-"
            waiting_text = f"{waiting_time:.4f}"
            service_text = f"{service_time:.4f}"
            e2e_text = f"{e2e_delay:.4f}"

        elif task_id in state.failed_tasks:
            status = "FAILED"
            end_text = f"{end_or_fail_time:.2f}" if end_or_fail_time is not None else "-"
            waiting_text = "-"
            service_text = f"{service_time:.4f}" if service_time > 0 else "-"
            e2e_text = "-"

        else:
            status = "UNFINISHED"
            end_text = f"{end_or_fail_time:.2f}" if end_or_fail_time is not None else "-"
            waiting_text = "-"
            service_text = f"{service_time:.4f}" if service_time > 0 else "-"
            e2e_text = "-"

        print(
            f"{task_id:>4}  "
            f"{task.av_id:>3}  "
            f"{mec_sequence:<18.18}  "
            f"{task.generated_at:>9.2f}  "
            f"{end_text:>9}  "
            f"{waiting_text:>9}  "
            f"{service_text:>9}  "
            f"{e2e_text:>10}  "
            f"{task.tau:>8.2f}  "
            f"{status:<20}"
        )

    # --------------------------------------------------------
    # System summary
    # --------------------------------------------------------
    print("\nSYSTEM SUMMARY")
    print("-" * report_width)
    print(f"{'Completed Tasks':<34}: {completed_count}")
    print(f"{'Failed Tasks':<34}: {failed_count}")
    print(f"{'Success Rate':<34}: {success_rate:.2f} %")
    print(f"{'Failure Rate':<34}: {failure_rate:.2f} %")

    if completed_delays:
        print(f"{'Mean E2E Delay':<34}: {mean_e2e:.4f} s")
        print(f"{'Median E2E Delay':<34}: {median_e2e:.4f} s")
        print(f"{'Minimum E2E Delay':<34}: {min_e2e:.4f} s")
        print(f"{'Maximum E2E Delay':<34}: {max_e2e:.4f} s")
        print(
            f"{'Total Completed E2E Delay':<34}: "
            f"{total_completed_e2e:.4f} s"
        )
    else:
        print(f"{'Mean E2E Delay':<34}: -")
        print(f"{'Median E2E Delay':<34}: -")
        print(f"{'Minimum E2E Delay':<34}: -")
        print(f"{'Maximum E2E Delay':<34}: -")
        print(f"{'Total Completed E2E Delay':<34}: -")

    # --------------------------------------------------------
    # MEC assignment statistics
    # --------------------------------------------------------
    print("\nMEC UTILIZATION")
    print("-" * report_width)

    assignment_counts = {
        bs_id: 0
        for bs_id in sorted(SERVERS)
    }

    for bs_id in state.assignments.values():
        assignment_counts[bs_id] = assignment_counts.get(bs_id, 0) + 1

    print(
        f"{'MEC':<8}"
        f"{'Assigned SubTasks':>20}"
        f"{'Share of Assignments':>24}"
    )
    print("-" * 52)

    total_assignments = sum(assignment_counts.values())

    for bs_id in sorted(assignment_counts):
        count = assignment_counts[bs_id]
        share = (
            100.0 * count / total_assignments
            if total_assignments > 0 else 0.0
        )

        print(
            f"{('BS' + str(bs_id)):<8}"
            f"{count:>20}"
            f"{share:>23.2f}%"
        )

    print("-" * 52)
    print(
        f"{'Total':<8}"
        f"{total_assignments:>20}"
        f"{100.0 if total_assignments else 0.0:>23.2f}%"
    )

    # --------------------------------------------------------
    # Failure analysis
    # --------------------------------------------------------
    print("\nFAILURE ANALYSIS")
    print("-" * report_width)

    if not failed_tasks:
        print("No task failures were recorded.")
    else:
        for task_id in failed_tasks:
            task = state.active_tasks[task_id]
            ordered_subtasks = sorted(
                task.subtasks,
                key=lambda st: st.order,
            )

            assigned_keys = [
                (task_id, st.subtask_id)
                for st in ordered_subtasks
                if (task_id, st.subtask_id) in state.assignments
            ]

            unassigned_keys = [
                (task_id, st.subtask_id)
                for st in ordered_subtasks
                if (task_id, st.subtask_id) not in state.assignments
            ]

            if unassigned_keys:
                first_failed_subtask = unassigned_keys[0][1]
                failure_type = "FAILED BEFORE ASSIGNMENT"
                bs_text = "-"
            elif assigned_keys:
                first_failed_subtask = assigned_keys[-1][1]
                failure_type = "FAILED AFTER ASSIGNMENT"
                bs_text = f"BS{state.assignments[assigned_keys[-1]]}"
            else:
                first_failed_subtask = "-"
                failure_type = "FAILED"
                bs_text = "-"

            print(
                f"Task {task_id} / SubTask {first_failed_subtask} | "
                f"AV{task.av_id} | {bs_text} | {failure_type}"
            )

    print("=" * report_width)


# ============================================================
# Main
# ============================================================

if __name__ == "__main__":
    state = run_online_sumo_rasmha()
    print_final_report(state)