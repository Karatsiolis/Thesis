"""
Implementation of RASMHA (Route-Aware Subtask MEC Heuristic Algorithm) in an
online SUMO simulation.

Assumptions:
  - V2I communication only and execution on MEC only (no local execution),
  - no caching and no energy model,
  - each task consists of subtasks that are executed sequentially.

Operation:
  - From the route of each AV, the ordered list of MEC/BSs it will meet is
    computed. Coverage entry/exit times are not predicted.
  - For each ready subtask, a target MEC is chosen among the MECs on the
    route that have not yet been passed.
  - The AV waits until it actually enters the coverage of the target MEC,
    and then offloads, if capacity is available and deadline/tau are met.
  - Recovery: if the AV leaves the coverage before the result is returned,
    the execution is cancelled, the MEC is freed and the same subtask starts
    from the beginning on the next MEC of the route.
  - A subtask is completed only if, at its finish time, the AV is still
    inside the coverage of the same BS/MEC.
"""

