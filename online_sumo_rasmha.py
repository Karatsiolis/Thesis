# Online RASMHA decision
# ============================================================

def choose_online_assignment(
    task: Task,
    subtask: SubTask,
    current_time: float,
    reachable_bs: List[int],
    predicted_exit_times: Dict[int, float],
    state: OnlineState,
) -> Optional[ScheduledJob]:
    """
    Online greedy RASMHA decision.

    Επιλέγει, εκείνη τη στιγμή, ανάμεσα στα BS που είναι σε V2I range.
    Κριτήριο: ελάχιστο finish_time.

    Δεν περιμένει να τελειώσει το SUMO.
    Δεν χρησιμοποιεί offline windows.
    """

    best_job: Optional[ScheduledJob] = None
    best_finish = inf

    for bs_id in reachable_bs:
        server = SERVERS[bs_id]

        # Real concurrent capacity check
        if state.mec_load.get(bs_id, 0) >= server.C_max:
            continue

        R = V2I_RATE

        delay, u, c, r = total_subtask_delay(subtask, server, R)

        t_start = max(
            current_time,
            subtask.earliest_start,
            state.last_finish.get(task.task_id, task.generated_at),
        )

        t_finish = t_start + delay

        predicted_exit = predicted_exit_times.get(bs_id, current_time)

        # Το αποτέλεσμα πρέπει να επιστρέψει πριν φύγει από την κάλυψη
        if t_finish > predicted_exit:
            continue

        # Το subtask πρέπει να προλάβει το deadline
        if t_finish > subtask.deadline:
            continue

        if t_finish < best_finish:
            best_finish = t_finish
            best_job = ScheduledJob(
                task_id=task.task_id,
                subtask_id=subtask.subtask_id,
                av_id=task.av_id,
                bs_id=bs_id,
                start_time=t_start,
                finish_time=t_finish,
                delay=delay,
                upload_time=u,
                compute_time=c,
                return_time=r,
            )

    return best_job


def start_job(job: ScheduledJob, state: OnlineState) -> None:
    """
    Commits assignment and starts running subtask on MEC.
    """
    key = (job.task_id, job.subtask_id)

    state.running_jobs.append(job)

    state.assignments[key] = job.bs_id
    state.D[key] = job.delay
    state.start_times[key] = job.start_time
    state.finish_times[key] = job.finish_time

    state.mec_load[job.bs_id] = state.mec_load.get(job.bs_id, 0) + 1

    print(
        f"  t={job.start_time:.2f}s  "
        f"Task {job.task_id} / SubTask {job.subtask_id} από AV{job.av_id} "
        f"→ OFFLOAD στο BS{job.bs_id}"
    )

    print(
        f"            upload={job.upload_time:.4f}s | "
        f"compute={job.compute_time:.4f}s | "
        f"return={job.return_time:.4f}s | "
        f"finish={job.finish_time:.2f}s | "
        f"delay={job.delay:.4f}s"
    )


def complete_finished_jobs(current_time: float, state: OnlineState) -> None:
    """
    Ολοκληρώνει όσα running subtasks έχουν finish_time <= current_time.
    """
    for job in list(state.running_jobs):
        if job.finish_time <= current_time:
            state.running_jobs.remove(job)

            state.mec_load[job.bs_id] = max(
                0,
                state.mec_load.get(job.bs_id, 0) - 1,
            )

            task = state.active_tasks[job.task_id]
            key = (job.task_id, job.subtask_id)

            state.last_finish[job.task_id] = job.finish_time
            state.next_order[job.task_id] += 1

            print(
                f"  t={current_time:.2f}s  "
                f"Task {job.task_id} / SubTask {job.subtask_id} "
                f"ολοκληρώθηκε από BS{job.bs_id}"
            )

            # Έλεγχος αν ολοκληρώθηκε όλο το task
            next_st = get_next_subtask(task, state.next_order[job.task_id])

            if next_st is None:
                total_delay = sum(
                    state.D.get((task.task_id, st.subtask_id), inf)
                    for st in task.subtasks
                )

                state.task_delays[task.task_id] = total_delay
                state.completed_tasks.add(task.task_id)

                print(
                    f"  t={current_time:.2f}s  "
                    f"Task {task.task_id} ΟΛΟΚΛΗΡΩΘΗΚΕ | "
                    f"total_delay={total_delay:.4f}s"
                )


def fail_task(task: Task, state: OnlineState, reason: str) -> None:
    """
    Mark task and all remaining subtasks as failed.
    """
    if task.task_id in state.failed_tasks or task.task_id in state.completed_tasks:
        return

    state.failed_tasks.add(task.task_id)

    current_order = state.next_order.get(task.task_id, 0)

    for st in sorted(task.subtasks, key=lambda s: s.order):
        if st.order >= current_order:
            key = (task.task_id, st.subtask_id)
            if key not in state.assignments and key not in state.failed_subtasks:
                state.failed_subtasks.append(key)

    print(
        f"  Task {task.task_id} από AV{task.av_id} ΑΠΕΤΥΧΕ: {reason}"
    )


