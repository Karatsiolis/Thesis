"""
online_sumo_rasmha.py
=====================

Online SUMO + RASMHA integration για τη διπλωματική.

Διαφορά από την offline εκδοχή:
  - Δεν τρέχει πρώτα όλο το SUMO για να συλλέξει windows.
  - Σε κάθε simulationStep διαβάζει real-time θέση AV.
  - Όταν ένα task/subtask είναι έτοιμο, παίρνει εκείνη τη στιγμή απόφαση.
  - Το subtask offload γίνεται μόνο σε BS/MEC που είναι διαθέσιμο εκείνη τη στιγμή.
  - Εκτυπώνει real-time γεγονότα:
        AV μπαίνει/βγαίνει από BS
        task δημιουργείται
        subtask ανατίθεται σε MEC
        subtask ολοκληρώνεται
        task ολοκληρώνεται ή αποτυγχάνει

Μοντέλο:
  - V2I only
  - MEC-only execution
  - no caching
  - no migration
  - sequential subtasks
  - online greedy RASMHA decision
"""

