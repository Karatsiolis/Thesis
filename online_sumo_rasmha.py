def prepare_sumo():
    """
    Διαβάζει δίκτυο, βρίσκει edges, ξεκινά SUMO και εισάγει AVs.
    """
    net = sumolib.net.readNet(NET_FILE)

    bs_xy = {
        bs_id: net.convertLonLat2XY(lon, lat)
        for bs_id, (lon, lat) in BS_COORDS.items()
    }

    av_edges = {
        1: (find_edge(net, *AV1_START), find_edge(net, *AV1_END)),
        2: (find_edge(net, *AV2_START), find_edge(net, *AV2_END)),
    }

    traci.start(["sumo-gui", "-c", SUMOCFG])

    # Προσθήκη BS/MEC ως POIs
    for bs_id, (x, y) in bs_xy.items():
        traci.poi.add(
            f"BS{bs_id}",
            x,
            y,
            color=(255, 0, 0, 220),
            layer=10,
            width=10,
            height=10,
        )

    # Εισαγωγή οχημάτων
    for av_id, (start_edge, end_edge) in av_edges.items():
        stage = traci.simulation.findRoute(start_edge.getID(), end_edge.getID())

        if not stage.edges:
            raise RuntimeError(f"Δεν βρέθηκε διαδρομή για AV {av_id}")

        route_id = f"route_av{av_id}"
        veh_id = f"av{av_id}"

        traci.route.add(route_id, stage.edges)

        traci.vehicle.add(
            veh_id,
            route_id,
            depart="now",
            departLane="best",
            departSpeed="0",
        )

        print(
            f"AV {av_id} inserted | "
            f"length={stage.length:.0f} m | "
            f"est. travel={stage.travelTime:.1f} s"
        )

    return bs_xy, av_edges


