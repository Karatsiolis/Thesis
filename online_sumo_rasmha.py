def dist(p1, p2) -> float:
    """
    Euclidean distance σε SUMO x/y coordinates, δηλαδή σε μέτρα.
    """
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])


def find_edge(net, lon: float, lat: float, radius: float = 30):
    """
    Βρίσκει κοντινό drivable edge για passenger vehicle.
    """
    x, y = net.convertLonLat2XY(lon, lat)
    r = radius

    while r <= 500:
        neighbors = net.getNeighboringEdges(x, y, r)

        drivable = [
            (edge, d) for edge, d in neighbors
            if not edge.isSpecial() and edge.allows("passenger")
        ]

        if drivable:
            edge, _ = min(drivable, key=lambda item: item[1])
            return edge

        r *= 2

    raise RuntimeError(f"Δεν βρέθηκε drivable edge κοντά στο ({lat}, {lon})")


def upload_delay(subtask: SubTask, R_av_bs: float) -> float:
    return subtask.D_in / R_av_bs


def mec_compute_delay(subtask: SubTask, server: MECServer) -> float:
    return subtask.omega / server.f_alloc


def return_delay(subtask: SubTask, R_av_bs: float) -> float:
    return subtask.D_out / R_av_bs


def total_subtask_delay(
    subtask: SubTask,
    server: MECServer,
    R_av_bs: float,
) -> Tuple[float, float, float, float]:
    """
    Returns:
        total_delay, upload, compute, return
    """
    u = upload_delay(subtask, R_av_bs)
    c = mec_compute_delay(subtask, server)
    r = return_delay(subtask, R_av_bs)
    return u + c + r, u, c, r


def get_next_subtask(task: Task, next_order: int) -> Optional[SubTask]:
    for st in task.subtasks:
        if st.order == next_order:
            return st
    return None


def create_task_from_template(template: TaskTemplate, current_time: float) -> Task:
    """
    Δημιουργεί πραγματικό Task από template.
    Τα deadlines γίνονται absolute simulation times.
    """
    subtasks: List[SubTask] = []

    for spec in template.subtasks:
        subtasks.append(
            SubTask(
                subtask_id=spec.subtask_id,
                parent_task_id=template.task_id,
                D_in=spec.D_in,
                D_out=spec.D_out,
                omega=spec.omega,
                deadline=current_time + spec.relative_deadline,
                order=spec.order,
                earliest_start=current_time + spec.earliest_offset,
            )
        )

    return Task(
        task_id=template.task_id,
        av_id=template.av_id,
        subtasks=subtasks,
        tau=template.tau,
        generated_at=current_time,
    )


def estimate_exit_time_from_bs(
    current_time: float,
    current_pos: Tuple[float, float],
    previous_pos: Optional[Tuple[float, float]],
    previous_time: Optional[float],
    bs_pos: Tuple[float, float],
    coverage_radius: float,
    fallback_horizon: float = 8.0,
) -> float:
    """
    Online εκτίμηση του πότε το AV θα βγει από την κάλυψη του BS.

    Χρησιμοποιεί απλή γραμμική πρόβλεψη:
        θέση(t + dt) = θέση(t) + velocity * dt

    Αν δεν υπάρχει προηγούμενη θέση, δίνει ένα συντηρητικό horizon.
    """
    if previous_pos is None or previous_time is None:
        return current_time + fallback_horizon

    dt = current_time - previous_time
    if dt <= 0:
        return current_time + fallback_horizon

    vx = (current_pos[0] - previous_pos[0]) / dt
    vy = (current_pos[1] - previous_pos[1]) / dt

    speed = math.hypot(vx, vy)

    if speed < 0.1:
        return current_time + fallback_horizon

    dx = current_pos[0] - bs_pos[0]
    dy = current_pos[1] - bs_pos[1]

    # Solve |(dx,dy) + (vx,vy)*t|^2 = R^2
    a = vx * vx + vy * vy
    b = 2.0 * (dx * vx + dy * vy)
    c = dx * dx + dy * dy - coverage_radius * coverage_radius

    discriminant = b * b - 4.0 * a * c

    if discriminant < 0:
        return current_time + fallback_horizon

    sqrt_disc = math.sqrt(discriminant)
    root1 = (-b - sqrt_disc) / (2.0 * a)
    root2 = (-b + sqrt_disc) / (2.0 * a)

    positive_roots = [r for r in (root1, root2) if r > 0.05]

    if not positive_roots:
        return current_time + fallback_horizon

    exit_after = min(positive_roots)
    return current_time + exit_after


