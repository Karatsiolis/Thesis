@dataclass
class SubTask:
    """
    Atomic unit of computation assigned to exactly one MEC server via V2I.
    SubTask s+1 cannot begin until SubTask s has finished.
    """
    subtask_id: int
    parent_task_id: int
    D_in: float
    D_out: float
    omega: float
    deadline: float          # absolute deadline in SUMO simulation time
    order: int
    earliest_start: float    # absolute earliest start time


@dataclass
class Task:
    """
    A computation task generated by an autonomous vehicle.
    """
    task_id: int
    av_id: int
    subtasks: List[SubTask]
    tau: float               # relative total task delay requirement
    generated_at: float


@dataclass
class MECServer:
    """
    MEC server co-located with a BS/RSU.
    """
    bs_id: int
    F_total: float
    C_max: int

    @property
    def f_alloc(self) -> float:
        if self.C_max <= 0:
            raise ValueError(f"C_max must be > 0 for BS {self.bs_id}")
        return self.F_total / self.C_max


@dataclass
class SubTaskSpec:
    """
    Template για subtask πριν δημιουργηθεί πραγματικά στο simulation.
    Τα deadlines/earliest_start δίνονται σχετικά με το generation time του task.
    """
    subtask_id: int
    D_in: float
    D_out: float
    omega: float
    relative_deadline: float
    order: int
    earliest_offset: float = 0.0


@dataclass
class TaskTemplate:
    """
    Template για task που θα δημιουργηθεί online σε συγκεκριμένο simulation time.
    """
    task_id: int
    av_id: int
    generate_at: float
    tau: float
    subtasks: List[SubTaskSpec]


@dataclass
class ScheduledJob:
    """
    Running subtask job on a MEC server.
    """
    task_id: int
    subtask_id: int
    av_id: int
    bs_id: int
    start_time: float
    finish_time: float
    delay: float
    upload_time: float
    compute_time: float
    return_time: float


@dataclass
class OnlineState:
    """
    Runtime state of online scheduler.
    """
    active_tasks: Dict[int, Task] = field(default_factory=dict)
    completed_tasks: set[int] = field(default_factory=set)
    failed_tasks: set[int] = field(default_factory=set)

    next_order: Dict[int, int] = field(default_factory=dict)
    last_finish: Dict[int, float] = field(default_factory=dict)

    running_jobs: List[ScheduledJob] = field(default_factory=list)

    assignments: Dict[Tuple[int, int], int] = field(default_factory=dict)
    D: Dict[Tuple[int, int], float] = field(default_factory=dict)
    start_times: Dict[Tuple[int, int], float] = field(default_factory=dict)
    finish_times: Dict[Tuple[int, int], float] = field(default_factory=dict)

    task_delays: Dict[int, float] = field(default_factory=dict)
    failed_subtasks: List[Tuple[int, int]] = field(default_factory=list)

    # Real concurrent load per BS
    mec_load: Dict[int, int] = field(default_factory=dict)

    # Για να μην τυπώνει κάθε δευτερόλεπτο "waiting"
    last_wait_log: Dict[Tuple[int, int], float] = field(default_factory=dict)


