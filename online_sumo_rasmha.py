def run_online_sumo_rasmha() -> OnlineState:
    """
    Ενιαία online προσομοίωση SUMO + RASMHA.
    """
    print("── Online SUMO + RASMHA simulation ───────────────────")

    bs_xy, av_edges = prepare_sumo()

    state = OnlineState(
        mec_load={bs_id: 0 for bs_id in SERVERS}
    )

    generated_task_ids: set[int] = set()
    target_vehicles = {f"av{av_id}" for av_id in av_edges}

    # Coverage state για enter/exit logs
    in_range: Dict[int, Dict[int, bool]] = {
        av_id: {bs_id: False for bs_id in BS_COORDS}
        for av_id in av_edges
    }

    # Για πρόβλεψη εξόδου από coverage
    previous_positions: Dict[int, Tuple[float, float]] = {}
    previous_times: Dict[int, float] = {}

    MAX_SIM_TIME = 140.0
    WAIT_LOG_PERIOD = 5.0

    try:
        while traci.simulation.getTime() <= MAX_SIM_TIME:

            # Stop condition:
            # Όλα τα AV έφτασαν, όλα τα tasks δημιουργήθηκαν, και δεν τρέχει job.
            all_templates_generated = len(generated_task_ids) == len(TASK_TEMPLATES)

            if (
                not target_vehicles
                and all_templates_generated
                and not state.running_jobs
            ):
                break

            traci.simulationStep()
            t = traci.simulation.getTime()

            # ----------------------------------------------------
            # 1. Ολοκλήρωση jobs που τελείωσαν σε αυτό το time
            # ----------------------------------------------------
            complete_finished_jobs(t, state)

            # ----------------------------------------------------
            # 2. Έλεγχος αφίξεων AV
            # ----------------------------------------------------
            arrived = set(traci.simulation.getArrivedIDList())

            for veh_id in list(target_vehicles):
                if veh_id in arrived:
                    target_vehicles.remove(veh_id)
                    av_id = int(veh_id.replace("av", ""))

                    print(f"  t={t:.1f}s  {veh_id} έφτασε στον προορισμό")

                    # Αν υπάρχουν tasks αυτού του AV που δεν ολοκληρώθηκαν, θα αποτύχουν
                    for task in list(state.active_tasks.values()):
                        if (
                            task.av_id == av_id
                            and task.task_id not in state.completed_tasks
                            and task.task_id not in state.failed_tasks
                        ):
                            # Αν δεν έχει running job που να τελειώνει ήδη τώρα, αποτυχία
                            has_running = any(
                                job.task_id == task.task_id
                                for job in state.running_jobs
                            )

                            if has_running:
                                # Αν το όχημα εξαφανιστεί από SUMO ενώ τρέχει job,
                                # το θεωρούμε αποτυχία επιστροφής αποτελέσματος.
                                fail_task(
                                    task,
                                    state,
                                    reason=f"το AV{av_id} έφτασε/έφυγε πριν επιστραφεί το αποτέλεσμα",
                                )
                            else:
                                fail_task(
                                    task,
                                    state,
                                    reason=f"το AV{av_id} έφτασε χωρίς να ολοκληρωθεί το task",
                                )

            # ----------------------------------------------------
            # 3. Current coverage και predicted exit ανά AV/BS
            # ----------------------------------------------------
            current_reachable: Dict[int, List[int]] = {
                av_id: [] for av_id in av_edges
            }

            predicted_exit_times: Dict[int, Dict[int, float]] = {
                av_id: {} for av_id in av_edges
            }

            for av_id in av_edges:
                veh_id = f"av{av_id}"

                if veh_id not in traci.vehicle.getIDList():
                    continue

                pos = traci.vehicle.getPosition(veh_id)
                previous_pos = previous_positions.get(av_id)
                previous_time = previous_times.get(av_id)

                for bs_id, bs_pos in bs_xy.items():
                    inside = dist(pos, bs_pos) <= BS_COVERAGE_M

                    if inside:
                        current_reachable[av_id].append(bs_id)

                        predicted_exit = estimate_exit_time_from_bs(
                            current_time=t,
                            current_pos=pos,
                            previous_pos=previous_pos,
                            previous_time=previous_time,
                            bs_pos=bs_pos,
                            coverage_radius=BS_COVERAGE_M,
                        )

                        predicted_exit_times[av_id][bs_id] = predicted_exit

                    # Enter event
                    if inside and not in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = True
                        print(f"  t={t:.1f}s  AV{av_id} → εντός BS{bs_id}")

                    # Exit event
                    elif not inside and in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = False
                        print(f"  t={t:.1f}s  AV{av_id} → εκτός  BS{bs_id}")

                previous_positions[av_id] = pos
                previous_times[av_id] = t

            # ----------------------------------------------------
            # 4. Online task generation
            # ----------------------------------------------------
            for template in TASK_TEMPLATES:
                if template.task_id in generated_task_ids:
                    continue

                if t >= template.generate_at:
                    av_id = template.av_id
                    veh_id = f"av{av_id}"

                    # Δημιουργούμε task μόνο αν το AV υπάρχει ακόμα στο SUMO
                    if veh_id in traci.vehicle.getIDList():
                        task = create_task_from_template(template, t)

                        state.active_tasks[task.task_id] = task
                        state.next_order[task.task_id] = 0
                        state.last_finish[task.task_id] = task.generated_at
                        generated_task_ids.add(task.task_id)

                        print(
                            f"\n  t={t:.1f}s  Δημιουργήθηκε Task {task.task_id} από AV{task.av_id}"
                        )

                        for st in sorted(task.subtasks, key=lambda s: s.order):
                            print(
                                f"            SubTask {st.subtask_id}: "
                                f"D_in={st.D_in:.1e} bits | "
                                f"omega={st.omega:.1e} cycles | "
                                f"deadline={st.deadline:.1f}s"
                            )

                    else:
                        generated_task_ids.add(template.task_id)
                        print(
                            f"  t={t:.1f}s  Task {template.task_id} δεν δημιουργήθηκε "
                            f"γιατί το AV{template.av_id} δεν υπάρχει πλέον"
                        )

            # ----------------------------------------------------
            # 5. Online RASMHA decisions για έτοιμα subtasks
            # ----------------------------------------------------
            for task_id, task in list(state.active_tasks.items()):

                if task_id in state.completed_tasks or task_id in state.failed_tasks:
                    continue

                # Αν ήδη τρέχει subtask αυτού του task, περιμένουμε
                if any(job.task_id == task_id for job in state.running_jobs):
                    continue

                next_order = state.next_order[task_id]
                subtask = get_next_subtask(task, next_order)

                if subtask is None:
                    continue

                # Δεν είναι ακόμα έτοιμο χρονικά
                if t < subtask.earliest_start:
                    continue

                # Το προηγούμενο subtask δεν έχει τελειώσει
                if t < state.last_finish.get(task_id, task.generated_at):
                    continue

                # Αν πέρασε το deadline χωρίς assignment
                if t > subtask.deadline:
                    fail_task(
                        task,
                        state,
                        reason=f"χάθηκε το deadline του SubTask {subtask.subtask_id}",
                    )
                    continue

                av_id = task.av_id
                reachable_bs = current_reachable.get(av_id, [])

                predicted_exits = predicted_exit_times.get(av_id, {})

                job = choose_online_assignment(
                    task=task,
                    subtask=subtask,
                    current_time=t,
                    reachable_bs=reachable_bs,
                    predicted_exit_times=predicted_exits,
                    state=state,
                )

                if job is not None:
                    start_job(job, state)

                else:
                    # Δεν υπάρχει διαθέσιμο MEC αυτή τη στιγμή.
                    # Δεν αποτυγχάνει αμέσως. Περιμένει μέχρι να βρει κάλυψη ή να χαθεί deadline.
                    key = (task.task_id, subtask.subtask_id)
                    last_log = state.last_wait_log.get(key, -inf)

                    if t - last_log >= WAIT_LOG_PERIOD:
                        state.last_wait_log[key] = t

                        if not reachable_bs:
                            reason = "κανένα BS σε V2I range"
                        else:
                            reason = f"BS διαθέσιμα {reachable_bs}, αλλά δεν προλαβαίνει πριν την έξοδο/deadline"

                        print(
                            f"  t={t:.1f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
                            f"περιμένει: {reason}"
                        )

        # Τέλος simulation: ό,τι έμεινε incomplete γίνεται failed
        for task in list(state.active_tasks.values()):
            if (
                task.task_id not in state.completed_tasks
                and task.task_id not in state.failed_tasks
            ):
                fail_task(
                    task,
                    state,
                    reason="τέλος προσομοίωσης χωρίς ολοκλήρωση",
                )

    finally:
        traci.close()

    return state


# ============================================================
# Final report
# ============================================================

def print_final_report(state: OnlineState) -> None:
    """
    Τελική περίληψη αποφάσεων.
    """
    print("\n" + "=" * 70)
    print("  ONLINE RASMHA FINAL REPORT")
    print("=" * 70)

    if not state.active_tasks:
        print("Δεν δημιουργήθηκαν tasks.")
        return

    for task_id in sorted(state.active_tasks):
        task = state.active_tasks[task_id]

        print(f"\nTask {task.task_id} από AV{task.av_id}")
        print(f"  generated_at = {task.generated_at:.2f}s")
        print(f"  tau          = {task.tau:.2f}s")

        print(
            f"  {'SubTask':<10} {'BS':>4} {'start':>10} "
            f"{'finish':>10} {'delay':>10} {'status'}"
        )
        print("  " + "-" * 62)

        for st in sorted(task.subtasks, key=lambda s: s.order):
            key = (task.task_id, st.subtask_id)

            if key in state.assignments:
                bs = state.assignments[key]
                ts = state.start_times[key]
                tf = state.finish_times[key]
                d = state.D[key]

                print(
                    f"  Sub {st.subtask_id:<6} BS {bs:>2}  "
                    f"{ts:>9.2f}s  {tf:>9.2f}s  {d:>9.4f}s  assigned"
                )

            elif key in state.failed_subtasks:
                print(
                    f"  Sub {st.subtask_id:<6} {'-':>4}  "
                    f"{'-':>10}  {'-':>10}  {'-':>10}  FAILED"
                )

            else:
                print(
                    f"  Sub {st.subtask_id:<6} {'-':>4}  "
                    f"{'-':>10}  {'-':>10}  {'-':>10}  not scheduled"
                )

        if task.task_id in state.completed_tasks:
            total_delay = state.task_delays.get(task.task_id, inf)
            status = "completed"

            if total_delay > task.tau:
                status = "completed but tau missed"

            print(f"  Total task delay: {total_delay:.4f}s [{status}]")

        elif task.task_id in state.failed_tasks:
            print("  Status: FAILED")

        else:
            print("  Status: unfinished")

    print("\nSummary:")
    print(f"  Completed tasks : {sorted(state.completed_tasks)}")
    print(f"  Failed tasks    : {sorted(state.failed_tasks)}")
    print(f"  Failed subtasks : {state.failed_subtasks}")

    feasible_total_cost = sum(
        state.task_delays[task_id]
        for task_id in state.completed_tasks
        if task_id not in state.failed_tasks
    )

    print(f"  Total system cost: {feasible_total_cost:.4f}s")


