"""
online_sumo_cmha_comparable.py
================================

Προσαρμοσμένη online έκδοση του CMHA του άρθρου για άμεση και δίκαιη
σύγκριση με τον RASMHA της διπλωματικής.

Κοινές παραδοχές με τον RASMHA:
  - ίδιο SUMO scenario, ίδια routes και ίδια πραγματική κίνηση AVs
  - ίδιο config.json και ίδιο random seed
  - ίδια tasks, ίδια sequential subtasks και ίδια deadlines/tau
  - ίδιοι MEC servers, F_total, C_max, V2I rate και coverage radius
  - V2I only και MEC-only execution
  - no caching, no local execution, no energy objective
  - ίδιος πραγματικός έλεγχος κάλυψης κατά την επιστροφή αποτελέσματος
  - ίδια τελική μορφή αποτελεσμάτων και ίδιες μετρικές

Πολιτική CMHA που διατηρείται από το άρθρο:
  - ο τρέχων MEC είναι ο Access BS
  - υπολογίζεται ο προβλεπόμενος υπολειπόμενος residence time T_w
  - αν T_access <= T_w, το subtask εκτελείται στον Access BS
  - διαφορετικά, μεταφέρεται μόνο στον αμέσως επόμενο Migration BS
  - η migration delay περιλαμβάνει upload, BS-to-BS transmission,
    MEC computation και result return, σύμφωνα με τη λογική της Eq. (16)
  - όταν πολλά subtasks είναι έτοιμα στο ίδιο SUMO step, εξετάζονται
    με greedy σειρά αυξανόμενου προβλεπόμενου κόστους, όπως στον CMHA

Η έκδοση αυτή αποτελεί controlled/adapted CMHA-W baseline. Δεν είναι η
αυτούσια coarse-grained έκδοση του άρθρου, επειδή η σύγκριση απαιτεί την ίδια
fine-grained δομή subtasks και τις ίδιες παραδοχές με τον RASMHA.
"""

