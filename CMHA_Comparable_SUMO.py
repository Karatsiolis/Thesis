@dataclass
class SubTask:
    """
    Atomic unit of computation assigned to exactly one MEC server via V2I.
    SubTask s+1 cannot begin until SubTask s has finished.
    """
    subtask_id: int
    parent_task_id: int
    D_in: float
    D_out: float
    omega: float
    deadline: float          # absolute deadline in SUMO simulation time
    order: int
    earliest_start: float    # absolute earliest start time


@dataclass
class Task:
    """
    A computation task generated by an autonomous vehicle.
    """
    task_id: int
    av_id: int
    subtasks: List[SubTask]
    tau: float               # relative total task delay requirement
    generated_at: float


@dataclass
class MECServer:
    """
    MEC server co-located with a BS/RSU.
    """
    bs_id: int
    F_total: float
    C_max: int

    @property
    def f_alloc(self) -> float:
        if self.C_max <= 0:
            raise ValueError(f"C_max must be > 0 for BS {self.bs_id}")
        return self.F_total / self.C_max


@dataclass
class SubTaskSpec:
    """
    Template για subtask πριν δημιουργηθεί πραγματικά στο simulation.
    Τα deadlines/earliest_start δίνονται σχετικά με το generation time του task.
    """
    subtask_id: int
    D_in: float
    D_out: float
    omega: float
    relative_deadline: float
    order: int
    earliest_offset: float = 0.0


@dataclass
class TaskTemplate:
    """
    Template για task που θα δημιουργηθεί online σε συγκεκριμένο simulation time.
    """
    task_id: int
    av_id: int
    generate_at: float
    tau: float
    subtasks: List[SubTaskSpec]


@dataclass
class ScheduledJob:
    """Subtask που εκτελείται απευθείας στον τρέχοντα Access BS."""
    task_id: int
    subtask_id: int
    av_id: int
    bs_id: int
    start_time: float
    finish_time: float
    delay: float
    upload_time: float
    compute_time: float
    return_time: float


@dataclass
class MigrationJob:
    """
    Subtask που ανεβαίνει στον Access BS και μεταδίδεται στον αμέσως
    επόμενο Migration BS, σύμφωνα με το mobility rule του CMHA.
    """
    task_id: int
    subtask_id: int
    av_id: int
    access_bs: int
    migration_bs: int
    start_time: float
    upload_time: float
    inter_bs_time: float
    compute_time: float
    return_time: float
    upload_end_time: float
    transfer_ready_time: float
    upload_checked: bool = False
    compute_start_time: Optional[float] = None
    compute_finish_time: Optional[float] = None
    result_ready: bool = False
    return_start_time: Optional[float] = None
    finish_time: Optional[float] = None
    capacity_acquired: bool = False

    @property
    def service_delay(self) -> float:
        return (
            self.upload_time
            + self.inter_bs_time
            + self.compute_time
            + self.return_time
        )


