def prepare_sumo():
    """
    Διαβάζει δίκτυο, βρίσκει edges, ξεκινά SUMO,
    εισάγει AVs και υπολογίζει ποιοι MEC servers βρίσκονται πάνω στη διαδρομή.

    Δεν υπολογίζει predicted coverage times.
    """
    net = sumolib.net.readNet(NET_FILE)

    # Μετατροπή BS/MEC lon/lat σε SUMO x/y coordinates
    bs_xy = {
        bs_id: net.convertLonLat2XY(lon, lat)
        for bs_id, (lon, lat) in BS_COORDS.items()
    }

    # Εύρεση start/end edges για όλα τα AVs που υπάρχουν στο config.json
    av_edges: Dict[int, Tuple[object, object]] = {}

    for av_id in sorted(VEHICLES.keys()):
        vehicle = VEHICLES[av_id]

        start_edge = find_edge(
            net,
            float(vehicle["start_lon"]),
            float(vehicle["start_lat"]),
        )

        end_edge = find_edge(
            net,
            float(vehicle["end_lon"]),
            float(vehicle["end_lat"]),
        )

        av_edges[av_id] = (start_edge, end_edge)

    # Εκκίνηση SUMO
    traci.start(["sumo-gui", "-c", SUMOCFG, "--step-length", "0.1"])

    # Προσθήκη BS/MEC ως POIs στο SUMO-GUI
    for bs_id, (x, y) in bs_xy.items():
        traci.poi.add(
            f"BS{bs_id}",
            x,
            y,
            color=(255, 0, 0, 220),
            layer=10,
            width=10,
            height=10,
        )

    route_mec_candidates_by_av: Dict[int, List[int]] = {}
    av_route_polylines: Dict[int, List[Tuple[float, float]]] = {}
    av_travel_times: Dict[int, float] = {}

    # Εισαγωγή όλων των AVs που υπάρχουν στο config.json
    for av_id, (start_edge, end_edge) in av_edges.items():
        stage = traci.simulation.findRoute(
            start_edge.getID(),
            end_edge.getID(),
        )

        if not stage.edges:
            raise RuntimeError(f"Δεν βρέθηκε διαδρομή για AV {av_id}")

        route_id = f"route_av{av_id}"
        veh_id = f"av{av_id}"

        traci.route.add(route_id, stage.edges)

        traci.vehicle.add(
            veh_id,
            route_id,
            depart="now",
            departLane="best",
            departSpeed="0",
        )

        # Χρώμα οχήματος από το config.json
        traci.vehicle.setColor(
            veh_id,
            get_vehicle_color(av_id),
        )

        route_polyline = build_route_polyline(net, list(stage.edges))

        route_candidates = compute_route_mec_candidates(
            route_polyline=route_polyline,
            bs_xy=bs_xy,
            coverage_radius=BS_COVERAGE_M,
        )

        route_mec_candidates_by_av[av_id] = route_candidates
        av_route_polylines[av_id] = route_polyline
        av_travel_times[av_id] = float(stage.travelTime)

        print(
            f"AV {av_id} inserted | "
            f"length={stage.length:.0f} m | "
            f"est. travel={stage.travelTime:.1f} s"
        )

        print(
            f"  Route MEC candidates for AV{av_id}: {route_candidates}"
        )

    return bs_xy, av_edges, route_mec_candidates_by_av, av_route_polylines, av_travel_times


# ============================================================
# Main online simulation
# ============================================================

def run_online_sumo_cmha() -> OnlineState:
    """
    Online comparable CMHA simulation.

    Η μόνη ουσιαστική διαφορά από τον RASMHA είναι η πολιτική επιλογής:
    current Access BS αν προλαβαίνει, αλλιώς migration μόνο στον επόμενο BS.
    """
    print("-- Online SUMO + Comparable CMHA simulation -------------------------------")

    (
        bs_xy,
        av_edges,
        route_mec_candidates_by_av,
        av_route_polylines,
        av_travel_times,
    ) = prepare_sumo()

    av_avg_speeds: Dict[int, float] = {}
    coverage_intervals_by_av: Dict[int, Dict[int, List[Tuple[float, float]]]] = {}

    for av_id, polyline in av_route_polylines.items():
        total_length = route_cumulative_distances(polyline)[-1]
        av_avg_speeds[av_id] = total_length / max(av_travel_times[av_id], 1e-9)
        coverage_intervals_by_av[av_id] = {
            bs_id: compute_route_coverage_intervals(
                route_polyline=polyline,
                bs_pos=bs_xy[bs_id],
                radius=BS_COVERAGE_M,
            )
            for bs_id in BS_COORDS
        }

    state = OnlineState(mec_load={bs_id: 0 for bs_id in SERVERS})

    generated_task_ids: set[int] = set()
    target_vehicles = {f"av{av_id}" for av_id in av_edges}

    in_range: Dict[int, Dict[int, bool]] = {
        av_id: {bs_id: False for bs_id in BS_COORDS}
        for av_id in av_edges
    }
    passed_bs_by_av: Dict[int, set[int]] = {
        av_id: set()
        for av_id in av_edges
    }

    max_sim_time = 140.0
    wait_log_period = 5.0

    try:
        while traci.simulation.getTime() <= max_sim_time:
            all_templates_generated = len(generated_task_ids) == len(TASK_TEMPLATES)

            if (
                not target_vehicles
                and all_templates_generated
                and not state.running_jobs
                and not state.migration_jobs
            ):
                break

            traci.simulationStep()
            t = traci.simulation.getTime()

            # ----------------------------------------------------
            # 1. Πραγματική θέση και κάλυψη AV/BS
            # ----------------------------------------------------
            current_reachable: Dict[int, List[int]] = {
                av_id: [] for av_id in av_edges
            }
            av_positions: Dict[int, Tuple[float, float]] = {}

            vehicle_ids = set(traci.vehicle.getIDList())

            for av_id in av_edges:
                veh_id = f"av{av_id}"
                if veh_id not in vehicle_ids:
                    continue

                pos = traci.vehicle.getPosition(veh_id)
                av_positions[av_id] = pos

                for bs_id, bs_pos in bs_xy.items():
                    inside = dist(pos, bs_pos) <= BS_COVERAGE_M

                    if inside:
                        current_reachable[av_id].append(bs_id)

                    if inside and not in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = True
                        print(f"  t={t:.1f}s  AV{av_id} -> εντός BS{bs_id}")
                    elif not inside and in_range[av_id][bs_id]:
                        in_range[av_id][bs_id] = False
                        passed_bs_by_av[av_id].add(bs_id)
                        print(f"  t={t:.1f}s  AV{av_id} -> εκτός BS{bs_id}")

            # ----------------------------------------------------
            # 2. Ενημέρωση access και migration jobs
            # ----------------------------------------------------
            update_access_jobs(t, state, current_reachable)
            update_migration_jobs(
                t,
                state,
                current_reachable,
                passed_bs_by_av,
            )

            # ----------------------------------------------------
            # 3. Αφίξεις AV
            # ----------------------------------------------------
            arrived = set(traci.simulation.getArrivedIDList())

            for veh_id in list(target_vehicles):
                if veh_id not in arrived:
                    continue

                target_vehicles.remove(veh_id)
                av_id = int(veh_id.replace("av", ""))
                print(f"  t={t:.1f}s  {veh_id} έφτασε στον προορισμό")

                for task in list(state.active_tasks.values()):
                    if (
                        task.av_id == av_id
                        and task.task_id not in state.completed_tasks
                        and task.task_id not in state.failed_tasks
                    ):
                        fail_task(
                            task,
                            state,
                            t,
                            reason=(
                                f"το AV{av_id} έφτασε/έφυγε πριν επιστραφεί "
                                f"το αποτέλεσμα"
                            ),
                        )

            # ----------------------------------------------------
            # 4. Ίδια online task generation με τον RASMHA
            # ----------------------------------------------------
            for template in TASK_TEMPLATES:
                if template.task_id in generated_task_ids:
                    continue

                if t < template.generate_at:
                    continue

                av_id = template.av_id
                veh_id = f"av{av_id}"

                if veh_id in traci.vehicle.getIDList():
                    task = create_task_from_template(template, t)
                    state.active_tasks[task.task_id] = task
                    state.next_order[task.task_id] = 0
                    state.last_finish[task.task_id] = task.generated_at
                    generated_task_ids.add(task.task_id)

                    print(
                        f"\n  t={t:.1f}s  Δημιουργήθηκε Task {task.task_id} "
                        f"από AV{task.av_id}"
                    )
                    for st in sorted(task.subtasks, key=lambda item: item.order):
                        print(
                            f"            SubTask {st.subtask_id}: "
                            f"D_in={st.D_in:.1e} bits | "
                            f"omega={st.omega:.1e} cycles | "
                            f"deadline={st.deadline:.1f}s"
                        )
                else:
                    generated_task_ids.add(template.task_id)
                    print(
                        f"  t={t:.1f}s  Task {template.task_id} δεν δημιουργήθηκε "
                        f"γιατί το AV{template.av_id} δεν υπάρχει πλέον"
                    )

            # ----------------------------------------------------
            # 5. Δημιουργία CMHA cost candidates για ready subtasks
            # ----------------------------------------------------
            candidates: List[Tuple[float, int, Task, SubTask, CMHADecision]] = []

            for task_id, task in list(state.active_tasks.items()):
                if task_id in state.completed_tasks or task_id in state.failed_tasks:
                    continue

                if any(job.task_id == task_id for job in state.running_jobs):
                    continue
                if any(job.task_id == task_id for job in state.migration_jobs):
                    continue

                subtask = get_next_subtask(task, state.next_order[task_id])
                if subtask is None:
                    continue

                if t < subtask.earliest_start:
                    continue
                if t < state.last_finish.get(task_id, task.generated_at):
                    continue

                if t > subtask.deadline or t > task.generated_at + task.tau:
                    fail_task(
                        task,
                        state,
                        t,
                        reason=f"χάθηκε deadline/tau του SubTask {subtask.subtask_id}",
                    )
                    continue

                av_id = task.av_id
                key = (task_id, subtask.subtask_id)
                reachable_bs = current_reachable.get(av_id, [])

                # Το άρθρο αποφασίζει όταν υπάρχει Access BS. Εκτός κάλυψης περιμένει.
                if not reachable_bs or av_id not in av_positions:
                    last_log = state.last_wait_log.get(key, -inf)
                    if t - last_log >= wait_log_period:
                        state.last_wait_log[key] = t
                        print(
                            f"  t={t:.1f}s  Task {task_id} / SubTask {subtask.subtask_id} "
                            f"περιμένει να εισέλθει σε Access BS"
                        )
                    continue

                access_bs = select_access_bs(
                    av_pos=av_positions[av_id],
                    reachable_bs=reachable_bs,
                    bs_xy=bs_xy,
                )
                if access_bs is None:
                    continue

                route_distance_now = av_route_distance(
                    av_positions[av_id],
                    av_route_polylines[av_id],
                )

                decision, reason = build_cmha_decision(
                    task=task,
                    subtask=subtask,
                    current_time=t,
                    access_bs=access_bs,
                    current_route_distance=route_distance_now,
                    avg_speed=av_avg_speeds[av_id],
                    route_candidates=route_mec_candidates_by_av.get(av_id, []),
                    passed_bs=passed_bs_by_av.get(av_id, set()),
                    coverage_intervals=coverage_intervals_by_av[av_id],
                )

                if decision is None:
                    fail_task(task, state, t, reason=reason)
                    continue

                # Η capacity feasibility ελέγχεται στον πραγματικό compute BS.
                compute_server = SERVERS[decision.compute_bs]
                if state.mec_load.get(decision.compute_bs, 0) >= compute_server.C_max:
                    last_log = state.last_wait_log.get(key, -inf)
                    if t - last_log >= wait_log_period:
                        state.last_wait_log[key] = t
                        print(
                            f"  t={t:.1f}s  Task {task_id} / SubTask {subtask.subtask_id} "
                            f"περιμένει capacity στο BS{decision.compute_bs}"
                        )
                    continue

                candidates.append(
                    (
                        decision.predicted_e2e_from_now,
                        task_id,
                        task,
                        subtask,
                        decision,
                    )
                )

            # ----------------------------------------------------
            # 6. Greedy min-cost επιλογή, όπως στον CMHA
            # ----------------------------------------------------
            candidates.sort(key=lambda item: (item[0], item[1]))

            for _, task_id, task, subtask, decision in candidates:
                if task_id in state.completed_tasks or task_id in state.failed_tasks:
                    continue
                if any(job.task_id == task_id for job in state.running_jobs):
                    continue
                if any(job.task_id == task_id for job in state.migration_jobs):
                    continue

                server = SERVERS[decision.compute_bs]
                if state.mec_load.get(decision.compute_bs, 0) >= server.C_max:
                    continue

                if decision.mode == "ACCESS":
                    start_access_job(task, subtask, decision, t, state)
                else:
                    start_migration_job(task, subtask, decision, t, state)

        # Τέλος simulation.
        for task in list(state.active_tasks.values()):
            if (
                task.task_id not in state.completed_tasks
                and task.task_id not in state.failed_tasks
            ):
                fail_task(
                    task,
                    state,
                    traci.simulation.getTime(),
                    reason="τέλος προσομοίωσης χωρίς ολοκλήρωση",
                )

    finally:
        traci.close()

    return state


