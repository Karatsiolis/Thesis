def build_route_polyline(net, edge_ids: List[str]) -> List[Tuple[float, float]]:
    """
    Χτίζει polyline της διαδρομής από τα shapes των SUMO edges.
    Τα σημεία είναι σε SUMO x/y coordinates, δηλαδή μέτρα.
    """
    points: List[Tuple[float, float]] = []

    for edge_id in edge_ids:
        edge = net.getEdge(edge_id)
        shape = edge.getShape()

        if not shape:
            continue

        for p in shape:
            point = (float(p[0]), float(p[1]))

            if not points or dist(points[-1], point) > 1e-6:
                points.append(point)

    if len(points) < 2:
        raise RuntimeError("Η διαδρομή δεν έχει αρκετά σημεία για polyline.")

    return points


def distance_point_to_segment(
    point: Tuple[float, float],
    seg_a: Tuple[float, float],
    seg_b: Tuple[float, float],
) -> float:
    """
    Απόσταση σημείου από ευθύγραμμο τμήμα.
    Χρησιμοποιείται για να δούμε αν η διαδρομή περνάει μέσα από κάλυψη BS.
    """
    px, py = point
    ax, ay = seg_a
    bx, by = seg_b

    abx = bx - ax
    aby = by - ay

    apx = px - ax
    apy = py - ay

    ab_len_sq = abx * abx + aby * aby

    if ab_len_sq == 0:
        return dist(point, seg_a)

    t = (apx * abx + apy * aby) / ab_len_sq
    t = max(0.0, min(1.0, t))

    closest = (
        ax + t * abx,
        ay + t * aby,
    )

    return dist(point, closest)


def route_passes_near_bs(
    route_polyline: List[Tuple[float, float]],
    bs_pos: Tuple[float, float],
    coverage_radius: float,
) -> bool:
    """
    Επιστρέφει True αν η διαδρομή περνάει μέσα από την περιοχή κάλυψης του BS.
    Δεν υπολογίζει χρόνους. Μόνο γεωμετρική σχέση διαδρομής-BS.
    """
    for i in range(1, len(route_polyline)):
        segment_start = route_polyline[i - 1]
        segment_end = route_polyline[i]

        d = distance_point_to_segment(
            point=bs_pos,
            seg_a=segment_start,
            seg_b=segment_end,
        )

        if d <= coverage_radius:
            return True

    return False


def route_cumulative_distances(
    route_polyline: List[Tuple[float, float]],
) -> List[float]:
    """
    Υπολογίζει cumulative distance πάνω στη route polyline.
    Χρησιμοποιείται μόνο για να βάλουμε τους MEC candidates στη σωστή σειρά route.
    Δεν χρησιμοποιείται για πρόβλεψη χρόνων.
    """
    cumulative = [0.0]

    for i in range(1, len(route_polyline)):
        cumulative.append(
            cumulative[-1] + dist(route_polyline[i - 1], route_polyline[i])
        )

    return cumulative


def closest_route_distance_to_bs(
    route_polyline: List[Tuple[float, float]],
    bs_pos: Tuple[float, float],
) -> Tuple[float, float]:
    """
    Βρίσκει:
      - την ελάχιστη γεωμετρική απόσταση BS-route
      - τη θέση πάνω στη route, ως distance από την αρχή της διαδρομής

    Αυτό ΔΕΝ προβλέπει χρόνο. Χρησιμοποιείται μόνο για ordering των MEC servers.
    """
    cumulative = route_cumulative_distances(route_polyline)

    best_distance = inf
    best_route_distance = inf

    for i in range(1, len(route_polyline)):
        seg_a = route_polyline[i - 1]
        seg_b = route_polyline[i]

        ax, ay = seg_a
        bx, by = seg_b
        px, py = bs_pos

        abx = bx - ax
        aby = by - ay
        ab_len_sq = abx * abx + aby * aby

        if ab_len_sq == 0.0:
            d = dist(bs_pos, seg_a)
            route_d = cumulative[i - 1]
        else:
            t = ((px - ax) * abx + (py - ay) * aby) / ab_len_sq
            t = max(0.0, min(1.0, t))

            closest = (
                ax + t * abx,
                ay + t * aby,
            )

            d = dist(bs_pos, closest)
            route_d = cumulative[i - 1] + t * dist(seg_a, seg_b)

        if d < best_distance:
            best_distance = d
            best_route_distance = route_d

    return best_distance, best_route_distance


def compute_route_mec_candidates(
    route_polyline: List[Tuple[float, float]],
    bs_xy: Dict[int, Tuple[float, float]],
    coverage_radius: float,
) -> List[int]:
    """
    Επιστρέφει τους BS/MEC servers που βρίσκονται πάνω στη διαδρομή του AV,
    ταξινομημένους με τη σειρά που τους συναντά το όχημα στη route.

    Δεν προβλέπει χρόνους εισόδου/εξόδου.
    Δεν κάνει offline scheduling.
    Υπολογίζει μόνο ποιοι MEC είναι υποψήφιοι και σε ποια σειρά route.
    """
    candidates_with_route_distance: List[Tuple[float, int]] = []

    for bs_id, bs_pos in bs_xy.items():
        min_distance, route_distance = closest_route_distance_to_bs(
            route_polyline=route_polyline,
            bs_pos=bs_pos,
        )

        if min_distance <= coverage_radius:
            candidates_with_route_distance.append((route_distance, bs_id))

    candidates_with_route_distance.sort()

    return [bs_id for _, bs_id in candidates_with_route_distance]


