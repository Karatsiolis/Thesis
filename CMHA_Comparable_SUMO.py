def print_final_report(state: OnlineState) -> None:
    """Ίδια βασική μορφή και ίδιες μετρικές με το RASMHA report."""
    report_width = 126

    print("\n" + "=" * report_width)
    print("CMHA-COMPARABLE - FINAL SIMULATION REPORT".center(report_width))
    print("=" * report_width)

    if not state.active_tasks:
        print("Δεν δημιουργήθηκαν tasks.")
        return

    tasks = [state.active_tasks[task_id] for task_id in sorted(state.active_tasks)]
    generated_tasks = len(tasks)
    generated_subtasks = sum(len(task.subtasks) for task in tasks)
    completed_tasks = sorted(state.completed_tasks)
    failed_tasks = sorted(state.failed_tasks)

    completed_count = len(completed_tasks)
    failed_count = len(failed_tasks)
    success_rate = 100.0 * completed_count / generated_tasks if generated_tasks else 0.0
    failure_rate = 100.0 * failed_count / generated_tasks if generated_tasks else 0.0

    completed_delays = sorted(
        state.task_delays[task_id]
        for task_id in completed_tasks
        if task_id in state.task_delays
    )
    total_completed_e2e = sum(completed_delays)
    mean_e2e = total_completed_e2e / len(completed_delays) if completed_delays else 0.0

    if completed_delays:
        n = len(completed_delays)
        middle = n // 2
        median_e2e = (
            completed_delays[middle]
            if n % 2 == 1
            else (completed_delays[middle - 1] + completed_delays[middle]) / 2.0
        )
        min_e2e = completed_delays[0]
        max_e2e = completed_delays[-1]
    else:
        median_e2e = min_e2e = max_e2e = 0.0

    print("\nSIMULATION CONFIGURATION")
    print("-" * report_width)
    print(f"{'Vehicles':<34}: {len(VEHICLES)}")
    print(f"{'MEC Servers':<34}: {len(SERVERS)}")
    print(f"{'Generated Tasks':<34}: {generated_tasks}")
    print(f"{'Generated SubTasks':<34}: {generated_subtasks}")
    print(f"{'V2I Rate':<34}: {V2I_RATE / 1.0e6:.2f} Mbps")
    print(f"{'BS-to-BS Rate':<34}: {BS_TO_BS_RATE / 1.0e6:.2f} Mbps")
    print(f"{'BS Coverage Radius':<34}: {BS_COVERAGE_M:.2f} m")

    print("\nTASK RESULTS")
    print("-" * report_width)
    header = (
        f"{'Task':>4}  {'AV':>3}  {'MEC Sequence':<18}  "
        f"{'Generated':>9}  {'End/Fail':>9}  {'Waiting':>9}  "
        f"{'Service':>9}  {'E2E Delay':>10}  {'Tau':>8}  {'Status':<20}"
    )
    print(header)
    print("-" * report_width)

    for task in tasks:
        task_id = task.task_id
        ordered_subtasks = sorted(task.subtasks, key=lambda st: st.order)
        assigned_bs = [
            state.assignments[(task_id, st.subtask_id)]
            for st in ordered_subtasks
            if (task_id, st.subtask_id) in state.assignments
        ]
        mec_sequence = " -> ".join(str(bs) for bs in assigned_bs) if assigned_bs else "-"
        service_time = sum(
            state.D.get((task_id, st.subtask_id), 0.0)
            for st in ordered_subtasks
        )

        if task_id in state.completed_tasks:
            end_time = max(
                state.finish_times[(task_id, st.subtask_id)]
                for st in ordered_subtasks
                if (task_id, st.subtask_id) in state.finish_times
            )
            e2e_delay = state.task_delays[task_id]
            waiting_time = max(0.0, e2e_delay - service_time)
            status = "COMPLETED" if e2e_delay <= task.tau else "TAU MISSED"
            end_text = f"{end_time:.2f}"
            waiting_text = f"{waiting_time:.4f}"
            service_text = f"{service_time:.4f}"
            e2e_text = f"{e2e_delay:.4f}"
        elif task_id in state.failed_tasks:
            end_text = f"{state.failure_times.get(task_id, 0.0):.2f}"
            waiting_text = "-"
            service_text = f"{service_time:.4f}" if service_time > 0 else "-"
            e2e_text = "-"
            status = "FAILED"
        else:
            end_text = waiting_text = e2e_text = "-"
            service_text = f"{service_time:.4f}" if service_time > 0 else "-"
            status = "UNFINISHED"

        print(
            f"{task_id:>4}  {task.av_id:>3}  {mec_sequence:<18.18}  "
            f"{task.generated_at:>9.2f}  {end_text:>9}  {waiting_text:>9}  "
            f"{service_text:>9}  {e2e_text:>10}  {task.tau:>8.2f}  {status:<20}"
        )

    print("\nSYSTEM SUMMARY")
    print("-" * report_width)
    print(f"{'Completed Tasks':<34}: {completed_count}")
    print(f"{'Failed Tasks':<34}: {failed_count}")
    print(f"{'Success Rate':<34}: {success_rate:.2f} %")
    print(f"{'Failure Rate':<34}: {failure_rate:.2f} %")

    if completed_delays:
        print(f"{'Mean E2E Delay':<34}: {mean_e2e:.4f} s")
        print(f"{'Median E2E Delay':<34}: {median_e2e:.4f} s")
        print(f"{'Minimum E2E Delay':<34}: {min_e2e:.4f} s")
        print(f"{'Maximum E2E Delay':<34}: {max_e2e:.4f} s")
        print(f"{'Total Completed E2E Delay':<34}: {total_completed_e2e:.4f} s")
    else:
        for label in (
            "Mean E2E Delay",
            "Median E2E Delay",
            "Minimum E2E Delay",
            "Maximum E2E Delay",
            "Total Completed E2E Delay",
        ):
            print(f"{label:<34}: -")

    print("\nMEC UTILIZATION")
    print("-" * report_width)
    assignment_counts = {bs_id: 0 for bs_id in sorted(SERVERS)}
    for bs_id in state.assignments.values():
        assignment_counts[bs_id] = assignment_counts.get(bs_id, 0) + 1

    print(f"{'MEC':<8}{'Assigned SubTasks':>20}{'Share of Assignments':>24}")
    print("-" * 52)
    total_assignments = sum(assignment_counts.values())
    for bs_id in sorted(assignment_counts):
        count = assignment_counts[bs_id]
        share = 100.0 * count / total_assignments if total_assignments else 0.0
        print(f"{('BS' + str(bs_id)):<8}{count:>20}{share:>23.2f}%")
    print("-" * 52)
    print(f"{'Total':<8}{total_assignments:>20}{100.0 if total_assignments else 0.0:>23.2f}%")

    print("\nMIGRATION SUMMARY")
    print("-" * report_width)
    total_migrations = len(state.migration_pairs)
    successful_migrations = sum(
        1 for key in state.migration_pairs
        if key in state.completed_subtasks
    )
    failed_migrations = total_migrations - successful_migrations
    access_executions = sum(1 for mode in state.execution_modes.values() if mode == "ACCESS")
    print(f"{'Access-BS Executions':<34}: {access_executions}")
    print(f"{'Total Migrations':<34}: {total_migrations}")
    print(f"{'Successful Migrations':<34}: {successful_migrations}")
    print(f"{'Failed Migrations':<34}: {failed_migrations}")

    print("\nFAILURE ANALYSIS")
    print("-" * report_width)
    if not failed_tasks:
        print("No task failures were recorded.")
    else:
        for task_id in failed_tasks:
            task = state.active_tasks[task_id]
            current_order = state.next_order.get(task_id, 0)
            current_st = get_next_subtask(task, current_order)
            st_text = current_st.subtask_id if current_st is not None else "-"
            reason = state.failure_reasons.get(task_id, "Unknown failure")
            print(
                f"Task {task_id} / SubTask {st_text} | AV{task.av_id} | "
                f"t={state.failure_times.get(task_id, 0.0):.2f}s | {reason}"
            )

    print("=" * report_width)


