def inter_bs_delay(subtask: SubTask, rate: float) -> float:
    """Eq. (11): transmission delay μεταξύ Access BS και Migration BS."""
    return subtask.D_in / rate


def av_route_distance(
    av_pos: Tuple[float, float],
    route_polyline: List[Tuple[float, float]],
) -> float:
    """Προβολή της πραγματικής θέσης του AV πάνω στη route polyline."""
    cumulative = route_cumulative_distances(route_polyline)
    best_route_dist = 0.0
    best_geom_dist = inf

    for i in range(1, len(route_polyline)):
        ax, ay = route_polyline[i - 1]
        bx, by = route_polyline[i]
        px, py = av_pos
        abx, aby = bx - ax, by - ay
        ab_len_sq = abx * abx + aby * aby

        if ab_len_sq == 0.0:
            t = 0.0
        else:
            t = ((px - ax) * abx + (py - ay) * aby) / ab_len_sq
            t = max(0.0, min(1.0, t))

        closest = (ax + t * abx, ay + t * aby)
        geom_dist = dist(av_pos, closest)

        if geom_dist < best_geom_dist:
            best_geom_dist = geom_dist
            best_route_dist = (
                cumulative[i - 1]
                + t * dist(route_polyline[i - 1], route_polyline[i])
            )

    return best_route_dist


def compute_route_coverage_intervals(
    route_polyline: List[Tuple[float, float]],
    bs_pos: Tuple[float, float],
    radius: float,
) -> List[Tuple[float, float]]:
    """
    Υπολογίζει τα route-distance intervals στα οποία η route βρίσκεται
    μέσα στην κυκλική κάλυψη ενός BS. Χρησιμοποιείται για την πρόβλεψη
    residence time T_w και του αμέσως επόμενου Migration BS.
    """
    cumulative = route_cumulative_distances(route_polyline)
    raw_intervals: List[Tuple[float, float]] = []
    cx, cy = bs_pos

    for i in range(1, len(route_polyline)):
        ax, ay = route_polyline[i - 1]
        bx, by = route_polyline[i]
        dx = bx - ax
        dy = by - ay
        segment_length = math.hypot(dx, dy)

        if segment_length <= 1e-12:
            continue

        fx = ax - cx
        fy = ay - cy

        a = dx * dx + dy * dy
        b = 2.0 * (fx * dx + fy * dy)
        c = fx * fx + fy * fy - radius * radius
        discriminant = b * b - 4.0 * a * c

        inside_a = c <= 0.0
        bx_rel = bx - cx
        by_rel = by - cy
        inside_b = bx_rel * bx_rel + by_rel * by_rel <= radius * radius

        t_values = [0.0, 1.0]
        if discriminant >= 0.0:
            sqrt_disc = math.sqrt(max(0.0, discriminant))
            t1 = (-b - sqrt_disc) / (2.0 * a)
            t2 = (-b + sqrt_disc) / (2.0 * a)
            if 0.0 < t1 < 1.0:
                t_values.append(t1)
            if 0.0 < t2 < 1.0:
                t_values.append(t2)

        t_values = sorted(set(round(t, 12) for t in t_values))

        for left, right in zip(t_values[:-1], t_values[1:]):
            mid = (left + right) / 2.0
            mx = ax + mid * dx
            my = ay + mid * dy
            inside_mid = (
                (mx - cx) * (mx - cx)
                + (my - cy) * (my - cy)
                <= radius * radius + 1e-9
            )

            if inside_mid:
                s_start = cumulative[i - 1] + left * segment_length
                s_end = cumulative[i - 1] + right * segment_length
                raw_intervals.append((s_start, s_end))

        # Περιπτώσεις ολόκληρου segment μέσα στον κύκλο χωρίς ρίζες.
        if discriminant < 0.0 and inside_a and inside_b:
            raw_intervals.append((cumulative[i - 1], cumulative[i]))

    if not raw_intervals:
        return []

    raw_intervals.sort()
    merged: List[List[float]] = []

    for start_s, end_s in raw_intervals:
        if not merged or start_s > merged[-1][1] + 1e-6:
            merged.append([start_s, end_s])
        else:
            merged[-1][1] = max(merged[-1][1], end_s)

    return [(start_s, end_s) for start_s, end_s in merged]


def current_coverage_interval(
    intervals: List[Tuple[float, float]],
    route_distance: float,
) -> Optional[Tuple[float, float]]:
    for start_s, end_s in intervals:
        if start_s - 1e-3 <= route_distance <= end_s + 1e-3:
            return start_s, end_s
    return None


def next_coverage_interval(
    intervals: List[Tuple[float, float]],
    route_distance: float,
) -> Optional[Tuple[float, float]]:
    for start_s, end_s in intervals:
        if end_s > route_distance + 1e-3:
            return start_s, end_s
    return None


def select_access_bs(
    av_pos: Tuple[float, float],
    reachable_bs: List[int],
    bs_xy: Dict[int, Tuple[float, float]],
) -> Optional[int]:
    """Το πλησιέστερο πραγματικά reachable BS γίνεται Access BS."""
    if not reachable_bs:
        return None
    return min(reachable_bs, key=lambda bs_id: dist(av_pos, bs_xy[bs_id]))


def find_next_migration_bs(
    access_bs: int,
    current_route_distance: float,
    access_exit_distance: float,
    route_candidates: List[int],
    passed_bs: set[int],
    coverage_intervals: Dict[int, List[Tuple[float, float]]],
) -> Tuple[Optional[int], Optional[Tuple[float, float]]]:
    """Βρίσκει μόνο τον αμέσως επόμενο BS της route, όπως στο άρθρο."""
    future: List[Tuple[float, int, Tuple[float, float]]] = []

    for bs_id in route_candidates:
        if bs_id == access_bs or bs_id in passed_bs:
            continue

        interval = next_coverage_interval(
            coverage_intervals.get(bs_id, []),
            current_route_distance,
        )
        if interval is None:
            continue

        entry_s, exit_s = interval
        if exit_s <= current_route_distance + 1e-3:
            continue

        # Προτιμάται το πρώτο coverage interval μετά την έξοδο από Access BS.
        ordering_entry = max(entry_s, access_exit_distance)
        future.append((ordering_entry, bs_id, interval))

    if not future:
        return None, None

    _, bs_id, interval = min(future, key=lambda item: (item[0], item[1]))
    return bs_id, interval


def build_cmha_decision(
    task: Task,
    subtask: SubTask,
    current_time: float,
    access_bs: int,
    current_route_distance: float,
    avg_speed: float,
    route_candidates: List[int],
    passed_bs: set[int],
    coverage_intervals: Dict[int, List[Tuple[float, float]]],
) -> Tuple[Optional[CMHADecision], str]:
    """
    Προσαρμογή των γραμμών 5-15 του Algorithm 1 για q=0, MEC-only.

    - T_access <= T_w  -> Access BS
    - T_access >  T_w  -> αμέσως επόμενος Migration BS
    """
    access_interval = current_coverage_interval(
        coverage_intervals.get(access_bs, []),
        current_route_distance,
    )

    if access_interval is None:
        return None, "δεν υπολογίστηκε έγκυρο residence interval για τον Access BS"

    _, access_exit_s = access_interval
    residence_time = max(
        0.0,
        (access_exit_s - current_route_distance) / max(avg_speed, 1e-9),
    )

    access_server = SERVERS[access_bs]
    access_delay, upload_t, compute_t, return_t = total_subtask_delay(
        subtask,
        access_server,
        V2I_RATE,
    )

    task_deadline = task.generated_at + task.tau

    # CMHA no-migration branch: Eq. (14) <= residence time.
    if access_delay <= residence_time:
        predicted_finish = current_time + access_delay

        if predicted_finish > subtask.deadline:
            return None, "η εκτέλεση στον Access BS παραβιάζει το subtask deadline"
        if predicted_finish > task_deadline:
            return None, "η εκτέλεση στον Access BS παραβιάζει το συνολικό tau"

        return CMHADecision(
            mode="ACCESS",
            access_bs=access_bs,
            compute_bs=access_bs,
            migration_bs=None,
            residence_time=residence_time,
            predicted_finish_time=predicted_finish,
            predicted_e2e_from_now=access_delay,
            upload_time=upload_t,
            inter_bs_time=0.0,
            compute_time=compute_t,
            return_time=return_t,
        ), ""

    # CMHA migration branch: επιτρέπεται μόνο προς τον επόμενο BS.
    migration_bs, migration_interval = find_next_migration_bs(
        access_bs=access_bs,
        current_route_distance=current_route_distance,
        access_exit_distance=access_exit_s,
        route_candidates=route_candidates,
        passed_bs=passed_bs,
        coverage_intervals=coverage_intervals,
    )

    if migration_bs is None or migration_interval is None:
        return None, "δεν υπάρχει επόμενος Migration BS στη διαδρομή"

    migration_server = SERVERS[migration_bs]
    upload_t = upload_delay(subtask, V2I_RATE)
    bs_bs_t = inter_bs_delay(subtask, BS_TO_BS_RATE)
    compute_t = mec_compute_delay(subtask, migration_server)
    return_t = return_delay(subtask, V2I_RATE)

    migration_entry_s, _ = migration_interval
    time_until_migration_entry = max(
        0.0,
        (migration_entry_s - current_route_distance) / max(avg_speed, 1e-9),
    )

    # Γενικευμένη online μορφή της Eq. (16): computation/transfer και
    # κίνηση του AV προς τον Migration BS εξελίσσονται παράλληλα.
    processing_before_return = upload_t + bs_bs_t + compute_t
    predicted_e2e = max(processing_before_return, time_until_migration_entry) + return_t
    predicted_finish = current_time + predicted_e2e

    if predicted_finish > subtask.deadline:
        return None, "η migration απόφαση παραβιάζει το subtask deadline"
    if predicted_finish > task_deadline:
        return None, "η migration απόφαση παραβιάζει το συνολικό tau"

    return CMHADecision(
        mode="MIGRATION",
        access_bs=access_bs,
        compute_bs=migration_bs,
        migration_bs=migration_bs,
        residence_time=residence_time,
        predicted_finish_time=predicted_finish,
        predicted_e2e_from_now=predicted_e2e,
        upload_time=upload_t,
        inter_bs_time=bs_bs_t,
        compute_time=compute_t,
        return_time=return_t,
    ), ""


def start_access_job(
    task: Task,
    subtask: SubTask,
    decision: CMHADecision,
    current_time: float,
    state: OnlineState,
) -> None:
    key = (task.task_id, subtask.subtask_id)
    finish_time = current_time + decision.predicted_e2e_from_now

    job = ScheduledJob(
        task_id=task.task_id,
        subtask_id=subtask.subtask_id,
        av_id=task.av_id,
        bs_id=decision.compute_bs,
        start_time=current_time,
        finish_time=finish_time,
        delay=decision.predicted_e2e_from_now,
        upload_time=decision.upload_time,
        compute_time=decision.compute_time,
        return_time=decision.return_time,
    )

    state.running_jobs.append(job)
    state.assignments[key] = decision.compute_bs
    state.access_assignments[key] = decision.access_bs
    state.execution_modes[key] = "ACCESS"
    state.D[key] = job.delay
    state.start_times[key] = current_time
    state.finish_times[key] = finish_time
    state.mec_load[decision.compute_bs] = state.mec_load.get(decision.compute_bs, 0) + 1

    print(
        f"  t={current_time:.2f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
        f"από AV{task.av_id} -> CMHA ACCESS στο BS{decision.compute_bs}"
    )
    print(
        f"            T_w={decision.residence_time:.4f}s | "
        f"upload={job.upload_time:.4f}s | compute={job.compute_time:.4f}s | "
        f"return={job.return_time:.4f}s | finish={finish_time:.2f}s"
    )


def start_migration_job(
    task: Task,
    subtask: SubTask,
    decision: CMHADecision,
    current_time: float,
    state: OnlineState,
) -> None:
    if decision.migration_bs is None:
        raise ValueError("Migration decision without migration_bs")

    key = (task.task_id, subtask.subtask_id)
    upload_end = current_time + decision.upload_time
    transfer_ready = upload_end + decision.inter_bs_time

    job = MigrationJob(
        task_id=task.task_id,
        subtask_id=subtask.subtask_id,
        av_id=task.av_id,
        access_bs=decision.access_bs,
        migration_bs=decision.migration_bs,
        start_time=current_time,
        upload_time=decision.upload_time,
        inter_bs_time=decision.inter_bs_time,
        compute_time=decision.compute_time,
        return_time=decision.return_time,
        upload_end_time=upload_end,
        transfer_ready_time=transfer_ready,
    )

    state.migration_jobs.append(job)
    state.assignments[key] = decision.compute_bs
    state.access_assignments[key] = decision.access_bs
    state.execution_modes[key] = "MIGRATION"
    state.migration_pairs[key] = (decision.access_bs, decision.migration_bs)
    state.D[key] = job.service_delay
    state.start_times[key] = current_time

    print(
        f"  t={current_time:.2f}s  Task {task.task_id} / SubTask {subtask.subtask_id} "
        f"από AV{task.av_id} -> CMHA MIGRATION BS{decision.access_bs}->BS{decision.migration_bs}"
    )
    print(
        f"            T_w={decision.residence_time:.4f}s | "
        f"upload={job.upload_time:.4f}s | BS-BS={job.inter_bs_time:.4f}s | "
        f"compute={job.compute_time:.4f}s | return={job.return_time:.4f}s | "
        f"predicted_finish={decision.predicted_finish_time:.2f}s"
    )


def complete_subtask(
    task: Task,
    subtask_id: int,
    finish_time: float,
    compute_bs: int,
    state: OnlineState,
) -> None:
    key = (task.task_id, subtask_id)
    state.finish_times[key] = finish_time
    state.completed_subtasks.add(key)
    state.last_finish[task.task_id] = finish_time
    state.next_order[task.task_id] += 1

    print(
        f"  t={finish_time:.2f}s  Task {task.task_id} / SubTask {subtask_id} "
        f"ολοκληρώθηκε στο BS{compute_bs} και το αποτέλεσμα επιστράφηκε στο AV{task.av_id}"
    )

    next_st = get_next_subtask(task, state.next_order[task.task_id])
    if next_st is None:
        total_delay = finish_time - task.generated_at
        state.task_delays[task.task_id] = total_delay
        state.completed_tasks.add(task.task_id)

        print(
            f"  t={finish_time:.2f}s  Task {task.task_id} ΟΛΟΚΛΗΡΩΘΗΚΕ | "
            f"total_delay={total_delay:.4f}s"
        )


def update_access_jobs(
    current_time: float,
    state: OnlineState,
    current_reachable: Dict[int, List[int]],
) -> None:
    for job in list(state.running_jobs):
        if job.task_id in state.failed_tasks:
            state.running_jobs.remove(job)
            continue

        if job.finish_time > current_time:
            continue

        state.running_jobs.remove(job)
        state.mec_load[job.bs_id] = max(0, state.mec_load.get(job.bs_id, 0) - 1)
        task = state.active_tasks[job.task_id]

        if job.bs_id not in current_reachable.get(job.av_id, []):
            fail_task(
                task,
                state,
                current_time,
                reason=(
                    f"το αποτέλεσμα του SubTask {job.subtask_id} δεν επέστρεψε, "
                    f"επειδή το AV{job.av_id} βγήκε από την κάλυψη του BS{job.bs_id}"
                ),
            )
            continue

        complete_subtask(
            task=task,
            subtask_id=job.subtask_id,
            finish_time=job.finish_time,
            compute_bs=job.bs_id,
            state=state,
        )


def update_migration_jobs(
    current_time: float,
    state: OnlineState,
    current_reachable: Dict[int, List[int]],
    passed_bs_by_av: Dict[int, set[int]],
) -> None:
    for job in list(state.migration_jobs):
        if job.task_id in state.failed_tasks:
            state.migration_jobs.remove(job)
            continue

        task = state.active_tasks[job.task_id]
        subtask = next(
            st for st in task.subtasks
            if st.subtask_id == job.subtask_id
        )

        if current_time > subtask.deadline or current_time > task.generated_at + task.tau:
            fail_task(
                task,
                state,
                current_time,
                reason=f"η migration του SubTask {job.subtask_id} έχασε deadline/tau",
            )
            continue

        # Το upload πρέπει να ολοκληρωθεί όσο το AV βρίσκεται στον Access BS.
        if not job.upload_checked and current_time >= job.upload_end_time:
            if job.access_bs not in current_reachable.get(job.av_id, []):
                fail_task(
                    task,
                    state,
                    current_time,
                    reason=(
                        f"το upload του SubTask {job.subtask_id} δεν ολοκληρώθηκε "
                        f"πριν το AV{job.av_id} φύγει από το BS{job.access_bs}"
                    ),
                )
                continue
            job.upload_checked = True

        # Όταν το input φτάσει στον Migration BS, ξεκινά computation αν υπάρχει capacity.
        if (
            current_time >= job.transfer_ready_time
            and job.compute_start_time is None
        ):
            server = SERVERS[job.migration_bs]
            if state.mec_load.get(job.migration_bs, 0) < server.C_max:
                job.compute_start_time = current_time
                job.compute_finish_time = current_time + job.compute_time
                job.capacity_acquired = True
                state.mec_load[job.migration_bs] = state.mec_load.get(job.migration_bs, 0) + 1

                print(
                    f"  t={current_time:.2f}s  Task {job.task_id} / SubTask {job.subtask_id}: "
                    f"ξεκίνησε computation στο Migration BS{job.migration_bs}"
                )

        if (
            job.compute_finish_time is not None
            and not job.result_ready
            and current_time >= job.compute_finish_time
        ):
            if job.capacity_acquired:
                state.mec_load[job.migration_bs] = max(
                    0,
                    state.mec_load.get(job.migration_bs, 0) - 1,
                )
                job.capacity_acquired = False

            job.result_ready = True
            print(
                f"  t={current_time:.2f}s  Task {job.task_id} / SubTask {job.subtask_id}: "
                f"το αποτέλεσμα είναι έτοιμο στο BS{job.migration_bs}"
            )

        # Αν το AV προσπέρασε τον Migration BS πριν την επιστροφή, η migration απέτυχε.
        if (
            job.return_start_time is None
            and job.migration_bs in passed_bs_by_av.get(job.av_id, set())
        ):
            fail_task(
                task,
                state,
                current_time,
                reason=(
                    f"το AV{job.av_id} προσπέρασε το Migration BS{job.migration_bs} "
                    f"πριν επιστραφεί το αποτέλεσμα του SubTask {job.subtask_id}"
                ),
            )
            continue

        # Η επιστροφή αρχίζει όταν και το αποτέλεσμα είναι έτοιμο και το AV είναι στο target BS.
        if (
            job.result_ready
            and job.return_start_time is None
            and job.migration_bs in current_reachable.get(job.av_id, [])
        ):
            job.return_start_time = current_time
            job.finish_time = current_time + job.return_time
            state.finish_times[(job.task_id, job.subtask_id)] = job.finish_time

        if (
            job.finish_time is not None
            and current_time >= job.finish_time
        ):
            state.migration_jobs.remove(job)

            if job.migration_bs not in current_reachable.get(job.av_id, []):
                fail_task(
                    task,
                    state,
                    current_time,
                    reason=(
                        f"το αποτέλεσμα του SubTask {job.subtask_id} δεν επέστρεψε, "
                        f"επειδή το AV{job.av_id} βγήκε από το Migration BS{job.migration_bs}"
                    ),
                )
                continue

            complete_subtask(
                task=task,
                subtask_id=job.subtask_id,
                finish_time=job.finish_time,
                compute_bs=job.migration_bs,
                state=state,
            )


def fail_task(
    task: Task,
    state: OnlineState,
    current_time: float,
    reason: str,
) -> None:
    """Σημειώνει task ως failed και ελευθερώνει τυχόν MEC capacity."""
    if task.task_id in state.failed_tasks or task.task_id in state.completed_tasks:
        return

    state.failed_tasks.add(task.task_id)
    state.failure_reasons[task.task_id] = reason
    state.failure_times[task.task_id] = current_time

    for job in list(state.running_jobs):
        if job.task_id == task.task_id:
            state.running_jobs.remove(job)
            state.mec_load[job.bs_id] = max(
                0,
                state.mec_load.get(job.bs_id, 0) - 1,
            )

    for job in list(state.migration_jobs):
        if job.task_id == task.task_id:
            state.migration_jobs.remove(job)
            if job.capacity_acquired:
                state.mec_load[job.migration_bs] = max(
                    0,
                    state.mec_load.get(job.migration_bs, 0) - 1,
                )

    current_order = state.next_order.get(task.task_id, 0)
    for st in sorted(task.subtasks, key=lambda item: item.order):
        if st.order >= current_order:
            key = (task.task_id, st.subtask_id)
            if key not in state.failed_subtasks:
                state.failed_subtasks.append(key)

    print(f"  Task {task.task_id} από AV{task.av_id} ΑΠΕΤΥΧΕ: {reason}")


